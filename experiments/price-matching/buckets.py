# -*- coding: utf-8 -*-
"""Собрать тестовый набор для модели: 437 живых строк прайсов -> корзины A-F.

    python3 build_ref.py ref.json
    python3 buckets.py ref.json real-names.json llm_cases.json

Вторая команда собирает llm_cases.json целиком — с шапкой, с полем expect и
с поставщиком каждой строки. Это важнее, чем кажется: набор, который нечем
пересобрать, через месяц становится рукописью, и никто уже не скажет, почему
у строки такой ожидаемый ответ.

Корзины:
  A  правила справились           — контроль, модель не должна их ломать
  B  позиции нет в справочнике    — модель предлагает черновик карточки
  C  информация есть, не взяли    — правила отказались ИЛИ взяли не то число,
                                    хотя позиция в справочнике ЕСТЬ
  D  данных не хватает            — модель обязана отказаться и спросить
  E  не прокат                    — модель обязана отбросить
  F  заголовок раздела            — размера нет вовсе, заводить нечего

Основа разбиения — статус match.py. Поверх двух правок:
  1) RECLASS — строки, где статус врёт. Каждая проверена поиском по
     справочнику: позиция там ЕСТЬ, просто правила её не нашли.
  2) «неоднозначно» с ОДНИМ кандидатом — это не неоднозначность, а недоделка
     разборщика: «Балка 10» -> 10Б1 единственный. Такие уходят в C.
"""
import collections, json, re, sys
from match import Matcher
from prompt import KINDS

# Позиция в справочнике ЕСТЬ, правила её не нашли (проверено поиском):
#   «разнополочный» не разворачивается в «неравнополочный» -> 63x40x5 есть;
#   «Уголок стальной, 4х25» — поставщик пишет толщина x полка -> 25x25x4 есть;
#   «Круг стальной, ст. 3, 100 мм» — за размер взята марка «ст. 3»;
#   «Лист оцинкованный Ст08ПС 0,5х...» — за толщину взято «08» из марки;
#   «Лист рифленый ГОСТ 8568-77 3х1250х2500» — за толщину взята ширина 1250;
#   «Балка 12 9м», «Балка 14 12м» — за номер взята длина (9 м, 12 м);
#   «Труба ВГП40*3.5» — «вгп40» без пробела, правило ВГП не срабатывает.
RECLASS_C = {
    "Уголок горячекатаный разнополочный 63х40х5",
    "Уголок горячекатаный разнополочный 100х63х6",
    "Уголок горячекатаный разнополочный 100х63х8",
    "Уголок горячекатаный разнополочный 125х80х10",
    "Уголок горячекатаный разнополочный 200х125х14",
    "Уголок стальной, 4х25 мм", "Уголок стальной, 5х50 мм",
    "Уголок стальной, 10х140 мм", "Уголок стальной, 7х90 мм",
    "Уголок стальной, 8х125 мм", "Уголок стальной, 6х63 мм",
    "Круг стальной, ст. 3, 24 мм", "Круг стальной, ст. 3, 100 мм",
    "Круг стальной, ст. 3, 200 мм", "Труба ВГП40*3.5",
    "Лист оцинкованный Ст08ПС 0,5х1250х2500 мм",
    "Лист рифленый ГОСТ 8568-77 3х1250х2500 мм чечевица",
    "Лист 1000х3700 мм Ст3сп5 ТУ36.3611-5-89 ПВЛ-406",
    "Балка 12 9м ст3пс5/сп5", "Балка 14 12м ст3пс5/сп5", "Балка 18 12м С255",
}
# Разборщик сказал «неоднозначно», но позиции нет вовсе: гнутый швеллер у нас
# не заведён, 24М/30М — монорельс (ГОСТ 19425), 20Ш2/20Ш3 не существует
# (по ГОСТ Р 57837 у номера 20 только 20Ш1). Кандидаты, которые он показал, —
# чужие профили, брать их нельзя.
RECLASS_B = {"Швеллер гнутый 160х60х5мм L=12м",
             "Двутавровая балка (двутавр) 30М", "Балка 20Ш2, 20Ш3"}
FITTINGS = {"Переход 89х3,5-76х3,5 мм", "Отвод короткий ст. ДУ - 20 (26.9*2)"}
NO_SIZE = ("размер не найден", "толщина не найдена")
NOT_IN_REF = ("размера нет в справочнике", "вида нет в справочнике",
              "толщины нет в справочнике")


def bucket(raw, res):
    if raw in RECLASS_C:
        return "C"
    if raw in RECLASS_B:
        return "B"
    if raw in FITTINGS:
        return "E"
    if res["status"] == "совпало":
        return "A"
    if res["status"] == "неоднозначно":
        return "C" if len(res["matches"]) == 1 else "D"
    if res["status"] in NOT_IN_REF:
        return "B"
    return "F" if res["status"] in NO_SIZE else "?"


# ── ОЖИДАЕМЫЙ ОТВЕТ ────────────────────────────────────────────────────────
# Поле expect — главное в наборе: по нему считается «статус совпал». Пока оно
# проставлялось руками, набор нельзя было пересобрать, не потеряв его. Здесь
# то же правило, но записанное кодом.
#
# Серию полок ищем в СЫРОЙ строке, а не в нормализованной, и разными буквами
# для швеллера и двутавра. Иначе «12м» (длина) не отличить от серии: у
# швеллера серии У, П, Э, Л — буквы «м» среди них нет, и длина отсекается
# сама. У двутавра серия М существует (монорельс), и вот там отличить
# нельзя — см. MONORAIL.
# Перед номером не \b, а запрет на букву, цифру, точку и запятую: иначе
# «ст.3пс» читается как второй профиль «3П» (граница слова после точки есть),
# и «Швеллер 14П ст.3пс» становится строкой про две позиции.
NUMBER = r"(?<![\w.,])\d+(?:[.,]\d+)?\s*"
SERIES = {
    "Швеллер": re.compile(NUMBER + r"а?[упэл]\d?", re.I),
    "Двутавр": re.compile(NUMBER + r"[бшкд]\d?", re.I),
}
# «Балка 24М»: М — это и монорельс по ГОСТ 19425, и метры. Регистр тут
# единственная зацепка, поэтому он значим: «24М» спорно, «12м» — длина.
MONORAIL = re.compile(NUMBER + r"М(?![а-яё])")
# «Швеллер 8У/П» — поставщик одной строкой продаёт две позиции: 8У и 8П.
TWO_SERIES = re.compile(r"[упэл]\s*/\s*[упэл]", re.I)
# Гнутый профиль меряется в миллиметрах (160х60х5), а поля швеллера в
# контракте — номер и серия. Ни то ни другое не враньё.
BENT = re.compile(r"гнут", re.I)
DUAL = ["черновик", "не_хватает_данных"]


def ambiguous(kind, raw):
    """Строки, на которых честны ДВА ответа: собрать черновик по тому, что
    написано, или отказаться и спросить человека. Спорит здесь не модель с
    эталоном — спорит сама строка прайса, и требовать от модели угадать,
    какую из двух трактовок мы имели в виду, нечестно."""
    if kind not in SERIES:
        return False
    if TWO_SERIES.search(raw) or len(SERIES[kind].findall(raw)) > 1:
        return True                     # две позиции в одной строке
    if kind == "Двутавр" and MONORAIL.search(raw):
        return True                     # монорельс или метры
    return bool(BENT.search(raw) and SERIES[kind].search(raw) is None
                and re.search(r"\d", raw))   # гнутый с размером в мм


def expect(key, raw, res):
    """Какой статус ответа модели считается верным для этой строки."""
    if key == "E":
        return ["не_прокат"]
    kind = res["type"]
    if kind not in KINDS:
        # Лист, полоса, катанка, проволока: это прокат, но вида нет среди
        # наших двенадцати. Правило идёт раньше корзин D и F — «Лист
        # горячекатаный Ст3 сп/пс» без толщины всё равно не наш вид.
        return ["вид_вне_списка"]
    if key in ("D", "F"):
        return ["не_хватает_данных"]
    if ambiguous(kind, raw):
        return list(DUAL)
    if kind in SERIES and not SERIES[kind].search(raw):
        # «Швеллер 16», «Балка 10»: номер есть, серии полок нет. 16П и 16У —
        # разные позиции справочника, выбирать за человека нельзя.
        return ["не_хватает_данных"]
    return ["черновик"]


# ── ВЫБОРКА КОНТРОЛЬНОЙ КОРЗИНЫ ────────────────────────────────────────────

def pick_diverse(items, n):
    """n строк из корзины: круговой обход по паре (вид проката, поставщик).

    Пара, а не один вид. Разбор ломается не на виде, а на ФОРМАТЕ записи
    размера, и формат — свойство прайса: «100*100*3», «25х25х4», «Ø108*4,5»,
    «№8», «ДУ 15 х 2,5». Если ключом брать только вид, внутри вида пойдут
    подряд идущие строки одного файла, и контроль соберётся из двух прайсов
    из двенадцати — тридцать строк одного почерка.

    Кругов поэтому два. Внешний по видам, чтобы не потерять сортамент;
    внутренний по поставщикам, со сдвигом старта у каждого вида — иначе
    первый круг целиком достанется тому, кто в файле лежит первым.
    """
    by_pair, seen = collections.OrderedDict(), set()
    for raw, row, res in items:
        if raw in seen:
            continue
        seen.add(raw)
        by_pair.setdefault((res["type"], row.get("supplier")), []).append(
            (raw, row, res))

    pairs_of_kind = collections.OrderedDict()
    for kind, supplier in by_pair:
        pairs_of_kind.setdefault(kind, []).append((kind, supplier))

    lanes = []
    for shift, pairs in enumerate(pairs_of_kind.values()):
        lane, depth = [], 0
        total = sum(len(by_pair[p]) for p in pairs)
        while len(lane) < total:
            for j in range(len(pairs)):
                group = by_pair[pairs[(j + shift) % len(pairs)]]
                if depth < len(group):
                    lane.append(group[depth])
            depth += 1
        lanes.append(lane)

    out, depth = [], 0
    while len(out) < n:
        before = len(out)
        for lane in lanes:
            if depth < len(lane) and len(out) < n:
                out.append(lane[depth])
        if len(out) == before:
            break
        depth += 1
    return out


