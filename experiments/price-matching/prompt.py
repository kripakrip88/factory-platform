def build_messages(line, no_think_suffix=True):
    """Сообщения для /api/chat. System и few-shot неизменны — это важно:
    постоянный префикс переиспользуется кэшем и не тратит время на каждой
    строке прайса."""
    import json
    msgs = [{"role": "system",
             "content": SYSTEM + (NO_THINK if no_think_suffix else "")}]
    for raw, answer in FEWSHOT:
        msgs.append({"role": "user", "content": USER_TEMPLATE % raw})
        msgs.append({"role": "assistant",
                     "content": json.dumps(answer, ensure_ascii=False,
                                           separators=(",", ":"))})
    msgs.append({"role": "user", "content": USER_TEMPLATE % line})
    return msgs
