T = env["project.task"].with_context(tracking_disable=True, mail_create_nolog=True,
                                     mail_auto_subscribe_no_notify=True, mail_notrack=True)
for num, project, col, user, name, info in TASKS:
    st = stage(col)
    old = T.search([("name", "=", name), ("project_id", "=", project.id)], limit=1)
    if old:
        print("есть", old.id, name)
        continue
    vals = {"name": name, "project_id": project.id, "stage_id": st.id,
            "description": NOTE + ("<p>%s</p>" % info if info else "")}
    if user:
        vals["user_ids"] = [(6, 0, user.ids)]
    task = T.create(vals)
    if task.id != num:   # номер разошёлся — оставить старый номер в названии
        task.name = "№%d %s" % (num, name)
    print("создана", task.id, "(было №%d)" % num, col, task.name)

