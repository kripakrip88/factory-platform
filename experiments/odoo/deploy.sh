#!/bin/sh
# Деплой стенда Odoo (:8084) из репозитория.
#
# Запускать на сервере:  sh /opt/factory-platform/experiments/odoo/deploy.sh
# Поставить новый модуль: INSTALL="pmk_mail_ui" sh .../deploy.sh
#
# Раньше этот скрипт лежал в /tmp на сервере и не был нигде записан: любая
# чистка /tmp — и деплой восстанавливай по памяти. Теперь он в репозитории.
set -e

REPO="${REPO:-/opt/factory-platform}"
STAND="${STAND:-/opt/experiments/odoo}"
DEST="$STAND/addons-extra"
BRANCH="${BRANCH:-feature/experiment-carbon}"

# Наши модули — обновляются через -u на каждом деплое.
# pmk_bridge добавлен 23.09.2026. До этого он жил ТОЛЬКО в репозитории: на
# сервере файлов не было, в ir_module_module записи не было, а 790 служебных
# строк связи «справочник → карточка» в базе создали скрипты, запущенные
# руками. Связь держалась на данных модуля, которого Odoo не знает.
# pmk_flow добавлен 27.09.2026 — схема связей документов, форк чужого
# визуализатора (см. ниже). Ставится первый раз через INSTALL="pmk_flow":
# -u на неустановленный модуль Odoo молча пропускает.
# pmk_deal_sms добавлен 30.09.2026 (разбор UX, шаг 31) — мостик, который
# прячет кнопки «СМС» в списке сделок; вынесен из pmk_deal, чтобы удаление
# «SMS»/iap не снесло сделку ↔ расчёт. Первый раз: INSTALL="pmk_deal_sms".
# pmk_drawing добавлен 06.10.2026 (разбор UX, шаг 46) — просмотр чертежей DXF
# (ezdxf из образа) в ленте, почте и у детали лазера. Почта и лазер зовут его
# мягко ('pmk.drawing' in env), жёсткой зависимости нет. Первый раз:
# INSTALL="pmk_drawing" (вместе с обычным -u почты и лазера).
# pmk_telegram добавлен 07.10.2026 — бот в Телеграме: сделка из сообщения или
# скриншота. Первый раз: INSTALL="pmk_telegram"; токен и вебхук — README модуля.
# pmk_org добавлен 08.10.2026 (разбор UX, шаг 58) — справочник «Наши
# организации» и налоговый режим по датам. Первый раз: INSTALL="pmk_org" —
# хук установки заводит налоги режимов и первую организацию (ИП Чулков) и
# проставляет её в сделки и расчёты; бэкап базы — до.
# pmk_orders добавлен 08.10.2026 (разбор UX, шаг З-2) — «Счёт покупателю» из
# расчёта при «КП отправлено» (с редакциями) и планировщик «Заказы в работе»
# на штатных Проектах. Первый раз: INSTALL="pmk_orders base_automation" —
# «Правила автоматизации» ставятся этим же прогоном, но НЕ зависимостью
# pmk_orders (тянут sms: удаление «SMS» снесло бы планировщик). Тот же прогон
# -u pmk_org выполнит миграцию 19.0.1.1.0 (налоги режимов «в цене») —
# до первого счёта; бэкап базы — до.
# pmk_list_prefs добавлен 08.10.2026 (разбор UX, шаг 55) — колонки списков у
# каждого: ширины, порядок и видимость на сервере, «Сделать так у всех» у
# администратора. Своя таблица pmk_list_prefs, данных других модулей не
# трогает; стили — в живых файлах pmk_theme (раздел «Шаг 55»). Первый раз:
# INSTALL="pmk_list_prefs" (вместе с обычным -u pmk_theme).
# pmk_tech добавлен 08.10.2026 (разбор UX, шаг З-4) — «Технический расчёт»
# инженера к счёту покупателю и «Заявка на металл» в черновики закупок,
# меню «Закупки → Заявки на металл». Отдельно от pmk_orders: он зависит от
# purchase, и удаление «Закупок» не должно сносить планировщик. Тем же
# прогоном -u pmk_deal (главный расчёт сделки — без технических) и
# pmk_flow («Связи»). Первый раз: INSTALL="pmk_tech"; бэкап базы — до.
# pmk_bank добавлен 14.10.2026 — поступления из банка в Телеграм. Первый раз:
# INSTALL="pmk_bank"; токен и счёт — README модуля.
# pmk_sheet_nest добавлен 15.10.2026 — вкладка «Раскрой листа» в задании лазеру
# (движок sheet_nest в lib/, отдельным процессом, очередь общая с вентзонтами).
# pmk_cut_cost добавлен 15.10.2026 — «Купить» и «Металл к закупке» расчёта целыми
# хлыстами из раскроя сортамента (мостик pmk_cut ↔ pmk_bridge). Первый раз:
# INSTALL="pmk_cut_cost".
# pmk_butik добавлен 16.10.2026 — «Бутик» в «Калькуляторах»: спецификация таблицей как
# в Excel Бутова, короткая запись строкой. Первый раз: INSTALL="pmk_butik".
# pmk_sales_home добавлен 16.10.2026 — «Продажи → Главная»: плитки, дела на сегодня,
# воронка, почта, заказы, поступления. Первый раз: INSTALL="pmk_sales_home".
# pmk_prod_home добавлен 16.10.2026 — «Производство → Главная»; лазер, калькуляторы, раскрой,
# справочники — внутрь «Производства». Первый раз: INSTALL="pmk_prod_home".
# pmk_purchase_home добавлен 18.10.2026 — «Закупки → Главная». Первый раз: INSTALL="pmk_purchase_home".
# pmk_ai добавлен 18.10.2026 — ассистент ✦ (Claude), ключ вписывает Антон. Первый раз: INSTALL="pmk_ai".
# pmk_cloud добавлен 15.10.2026 — новые файлы раскроя в Облаке Mail.ru → группа
# Телеграма; пароль вписывает Антон (Настройки → Облако Mail.ru). Первый раз:
# INSTALL="pmk_sheet_nest pmk_cloud".
OURS="pmk_calc pmk_theme pmk_pdf pmk_cut pmk_mail_ui pmk_partner pmk_purchase pmk_dadata pmk_laser pmk_bridge pmk_deal pmk_deal_sms pmk_flow pmk_drawing pmk_telegram pmk_org pmk_orders pmk_list_prefs pmk_tech pmk_vent_nest pmk_moysklad pmk_bank pmk_sheet_nest pmk_cloud pmk_cut_cost pmk_butik pmk_sales_home pmk_prod_home pmk_purchase_home pmk_ai"
# pmk_vent_nest — раскрой вентзонтов (12.10.2026). Первый раз: INSTALL="pmk_vent_nest".
# pmk_moysklad — МойСклад → Odoo (12.10.2026). Первый раз: INSTALL="pmk_moysklad"; затем перенос
# «за всё время» из shell: env["pmk.moysklad"].sync_all(full=True) (крон до этого молчит).
# Вендорские — только раскладываются. -u им не нужен: мы правим в них код и
# переводы, а не данные, а лишнее обновление перезапускает их data-файлы.
#
# Тема, Team Inbox и tracking_manager добавлены 21.09.2026: до этого они жили
# ТОЛЬКО в addons-extra на сервере, вне git и вне этого списка. Одна неудачная
# команда — и тема, на которой стоит весь вид стенда, исчезла бы без следа.
# Теперь источник истины — репозиторий, как и у mail_client.
# codeerts_transaction_flow_visualizer добавлен 24.09.2026 и УБРАН отсюда
# 27.09.2026: решение владельца — не обновлять чужой модуль, а взять код себе.
# Теперь это наш pmk_flow (addons/pmk_flow, README там же).
# ⚠️ Убрать из списка ≠ удалить со стенда. Скрипт стирает в addons-extra
# только то, что раскладывает, поэтому папка старого модуля там остаётся и
# установленный модуль продолжает работать. Удаляется он руками: Приложения →
# «Transaction Flow Visualizer» → Удалить, потом папку из addons-extra.
VENDOR="mail_client theme_liquid_glass northlight_teaminbox tracking_manager techy_backend_theme theme_nexus"
# Модули, которые надо ПОСТАВИТЬ, а не обновить (через переменную окружения).
INSTALL="${INSTALL:-}"

echo "→ ветка $BRANCH"
cd "$REPO"
git fetch -q origin "$BRANCH"

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
git archive "origin/$BRANCH" experiments/odoo/addons experiments/odoo/vendor \
  | tar -x -C "$WORK"

# Гасим до раскладки: подмена файлов под работающим Odoo даёт странные
# полусостояния, а ALTER TABLE при -u упирается в блокировку от открытой формы.
cd "$STAND"
docker compose stop odoo >/dev/null 2>&1 || true

for M in $OURS; do
  SRC="$WORK/experiments/odoo/addons/$M"
  [ -d "$SRC" ] || { echo "НЕТ МОДУЛЯ В РЕПО: addons/$M"; exit 1; }
  rm -rf "$DEST/$M" && cp -r "$SRC" "$DEST/" && chmod -R a+rX "$DEST/$M"
done

for M in $VENDOR; do
  SRC="$WORK/experiments/odoo/vendor/$M"
  [ -d "$SRC" ] || { echo "НЕТ МОДУЛЯ В РЕПО: vendor/$M"; exit 1; }
  rm -rf "$DEST/$M" && cp -r "$SRC" "$DEST/" && chmod -R a+rX "$DEST/$M"
done
echo "→ разложено: $OURS | вендор: $VENDOR"

UPD="$OURS"
# I18N=1 — дозалить переводы вендорских модулей в базу. Строки кода (.po)
# читаются из файла и обновления не требуют, а метки полей, значения списков,
# подсказки и заголовки форм лежат в jsonb-колонках и попадают туда только при
# -u. Без --i18n-overwrite Odoo лишь доливает недостающие и НЕ заменяет уже
# записанные — то есть исправление перевода без этого флага не доедет.
[ -n "$I18N" ] && UPD="$UPD $VENDOR"
ARGS="-u $(echo $UPD | tr ' ' ',')"
[ -n "$I18N" ] && ARGS="$ARGS --i18n-overwrite"
[ -n "$INSTALL" ] && ARGS="$ARGS -i $(echo $INSTALL | tr ' ' ',')"
echo "→ odoo $ARGS"
# WARNING показываем наравне с ошибками: именно предупреждением Odoo сообщает,
# что наследуемое представление не применилось и было ВЫКЛЮЧЕНО. Прежний фильтр
# ловил только CRITICAL/ERROR, поэтому такая потеря проходила молча — карточка
# контрагента так и стояла без секций, а деплой писал «готово» (прецедент
# 2026-09-20). Шум чужих модулей (нет license/author в манифесте, незнакомые
# ключи конфига) отсеиваем отдельной строкой, иначе важное утонет в нём.
docker compose run --rm -T odoo odoo -d odoo $ARGS --stop-after-init 2>&1 \
  | grep -E "CRITICAL|ERROR|WARNING|Failed to|Modules loaded" \
  | grep -vE "Missing \`(license|author)\` key|unknown option '|missing --http-interface" \
  | tail -20

# Бандлы ассетов кэшируются в ir_attachment: без чистки сервер продолжит
# отдавать старый CSS/JS, сколько ни обновляй модули (CLAUDE.md, п. 8).
docker compose exec -T db psql -U odoo -d odoo -tAc \
  "DELETE FROM ir_attachment WHERE url LIKE '/web/assets/%';" >/dev/null

# Только старт. Раньше здесь стоял ещё и restart сразу следом — «чтобы сбросить
# кэш переводов в памяти процесса». Он был лишним: процесс гасится в начале
# скрипта (строка 36), поэтому стартует заведомо новый и никакого старого кэша
# в нём нет. Лишний перезапуск заставлял Odoo грузить реестр четыре раза подряд
# вместо двух — около пяти секунд с каждого деплоя на пустом месте
# (замер 21.09.2026: 86 загрузок реестра в логе, по 2,15-2,82 с каждая).
docker compose start odoo >/dev/null 2>&1
# Расчётчик раскроя (16.10.2026) держит worker.py в памяти — перезапуск, чтобы взял новый
# код. Не поднят (описание контейнеров стенда старое) — пропуск: Odoo считает у себя.
if [ -n "$(docker compose ps -q nest-worker 2>/dev/null)" ]; then
  docker compose restart nest-worker >/dev/null 2>&1 && echo "→ расчётчик перезапущен"
fi
echo "→ готово"
