NUM = r"\d+(?:[.,]\d+)?"
SEP = r"\s*[xх×X]\s*"


def _nums(label):
    return [float(n.replace(",", ".")) for n in re.findall(NUM, label)]


def _dims(label, count):
    """Числа размера «a x b x c» (x латинский, кириллический или ×, запятая или точка)."""
    tail = (r"(?:" + SEP + r"(" + NUM + r"))?") * (count - 1)
    m = re.match(r"^\s*(?:Ду)?(" + NUM + r")" + tail, label)
    if not m:
        return None
    vals = [float(g.replace(",", ".")) for g in m.groups() if g is not None]
    return vals


def _flanged(h, b, s, t):
    """Периметр (мм) и масса (кг/м) швеллера/двутавра без радиусов: 2h + 4b − 2s."""
    return 2 * h + 4 * b - 2 * s, (2 * b * t + (h - 2 * t) * s) * STEEL / 1e6


def surface(row):
    """(периметр, мм; масса по таблице, кг/м или None; ключ таблицы) или (None, ...) если не разобрали."""
    ptype, label = row["profile_type"], row["size_label"].strip()
    if ptype in ("Круг", "Арматура"):
        d = _dims(label.lstrip("dDØø⌀ "), 1)
        return (math.pi * d[0], None, None) if d else (None, None, None)
    if ptype == "Квадрат":
        d = _dims(label, 1)
        return (4 * d[0], None, None) if d else (None, None, None)
    if ptype == "Шестигранник":
        d = _dims(label.lstrip("SsЅ "), 1)
        return (2 * math.sqrt(3) * d[0], None, None) if d else (None, None, None)
    if ptype == "Полоса":
        d = _dims(label, 2)
        return (2 * (d[0] + d[1]), None, None) if d and len(d) == 2 else (None, None, None)
    if ptype == "Труба ВГП":
        try:
            return math.pi * float(row["outer_mm"].replace(",", ".")), None, None
        except ValueError:
            return None, None, None
    if ptype == "Труба круглая":
        d = _dims(label, 2)
        return (math.pi * d[0], None, None) if d else (None, None, None)
    if ptype in ("Труба профильная квадратная", "Труба профильная прямоугольная"):
        d = _dims(label, 3)
        if not d or len(d) < 2:
            return None, None, None
        if len(d) == 2:            # «40x3» — квадратная a x s
            d = [d[0], d[0], d[1]]
        a, b, s = d
        return 2 * (a + b), None, None
    if ptype == "Уголок равнополочный":
        d = _dims(label, 3)
        if not d or len(d) < 2:
            return None, None, None
        b, t = (d[0], d[1]) if len(d) == 2 else (d[0], d[2])
        return 4 * b - 2 * t, None, None
    if ptype == "Уголок неравнополочный":
        d = _dims(label, 3)
        if not d or len(d) != 3:
            return None, None, None
        return 2 * (d[0] + d[1]) - 2 * d[2], None, None
    if ptype == "Швеллер гнутый":
        d = _dims(label, 3)
        if not d or len(d) != 3:
            return None, None, None
        h, b, s = d
        return 2 * h + 4 * b - 2 * s, None, None
    if ptype == "Швеллер":
        key = label.replace(",", ".").replace(" ", "").replace("a", "а")
        dims = CHANNELS.get(key)
        if not dims:
            return None, None, None
        p, m = _flanged(*dims)
        return p, m, key
    if ptype == "Двутавр":
        key = label.replace(",", ".").replace(" ", "").upper().replace("B", "Б").replace("K", "К")
        if "8239" in row["gost"]:
            dims = IBEAMS_8239.get(key)
        elif "19425" in row["gost"]:
            dims = IBEAMS_M.get(key.replace("M", "М"))
        else:
            dims = IBEAMS.get(key)
        if not dims:
            return None, None, None
        p, m = _flanged(*dims)
        return p, m, key
    return None, None, None


def _parse_header(line):
    return line.rstrip("\r\n").split(",")


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if not a.startswith("--")]
    path = os.path.abspath(args[0] if args else DEFAULT_CSV)
    with open(path, encoding="utf-8", newline="") as fh:
        lines = fh.readlines()
    header = _parse_header(lines[0])
    if header[-1] != "surface_per_meter":
        sys.exit("последняя колонка не surface_per_meter: %s" % header[-1])

    out = [lines[0]]
    filled, unparsed, mass_bad, changed_old = {}, [], [], []
    for ln, line in enumerate(lines[1:], start=2):
        body = line.rstrip("\r\n")
        eol = line[len(body):]
        cells = body.split(",")
        if len(cells) != len(header):
            sys.exit("строка %s: %s колонок вместо %s (кавычки?)" % (ln, len(cells), len(header)))
        row = dict(zip(header, cells))
        perim, tab_mass, key = surface(row)
        if perim is None:
            unparsed.append((ln, row["profile_type"], row["size_label"]))
            out.append(line)
            continue
        new = "%.4f" % (perim / 1000.0)
        old = row["surface_per_meter"]
        if old:
            changed_old.append((row["profile_type"], row["size_label"], old, new))
        filled[row["profile_type"]] = filled.get(row["profile_type"], 0) + 1
        if tab_mass is not None:
            try:
                csv_mass = float(row["mass_per_meter"].replace(",", "."))
            except ValueError:
                csv_mass = 0.0
            if csv_mass and abs(tab_mass - csv_mass) / csv_mass > MASS_TOL:
                mass_bad.append((row["profile_type"], row["size_label"], csv_mass, tab_mass, new))
        cells[-1] = new
        out.append(",".join(cells) + eol)

    print("Файл: %s" % path)
    print("Заполнено по типам:")
    for k in sorted(filled):
        print("  %-34s %4d" % (k, filled[k]))
    print("  итого %d из %d" % (sum(filled.values()), len(lines) - 1))
    print("Не разобрано (%d):" % len(unparsed))
    for u in unparsed:
        print("  строка %s: %s «%s»" % u)
    print("Масса по табличным размерам расходится с CSV больше %d %% (%d):"
          % (MASS_TOL * 100, len(mass_bad)))
    for pt, lab, cm, tm, new in mass_bad:
        print("  %s %s: CSV %.2f кг/м, по размерам %.2f (%+.1f %%), площадь %s"
              % (pt, lab, cm, tm, (tm - cm) / cm * 100, new))
    print("Было заполнено (старое → новое):")
    for pt, lab, old, new in changed_old:
        print("  %s %s: %s → %s" % (pt, lab, old, new))

    if check:
        return
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.writelines(out)
    print("Записано.")


if __name__ == "__main__":
    main(sys.argv[1:])
