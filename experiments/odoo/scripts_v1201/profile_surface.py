"""Площадь окраски погонного метра проката → колонка surface_per_meter (27.10.2026).

Зачем: строка «окраска / горячий цинк» в расчёте суммирует поверхность деталей изделия;
у проката без площади вклад 0 — колонна 2×13 м швеллера 30У давала 5,25 м² вместо ~31.

Площадь — полный наружный периметр сечения (обе стороны полок), м²/м:
  труба круглая D×s, ВГП — π·D (у ВГП наружный диаметр из колонки outer_mm);
  труба профильная a×b×s — 2(a+b) без скругления углов (Антон 27.10.2026: «как в таблицах
    расхода краски», 40×40 — 0,16; со скруглением было 0,150 — расход занижен);
  уголок b×t — 4b − 2t, неравнополочный B×b×t — 2(B+b) − 2t (радиусы не считаем);
  швеллер, двутавр — 2h + 4b − 2s по табличным h, b, s, t (радиусы не считаем, ≤2 %);
  швеллер гнутый h×b×s — 2h + 4b − 2s;
  круг, арматура d — π·d; квадрат a — 4a; шестигранник S — 2√3·S; полоса — 2(b+t).

Проверка размеров швеллеров и двутавров: площадь сечения A = 2bt + (h−2t)s (без радиусов),
масса A·7850 сравнивается с mass_per_meter; расхождение больше 8 % — строка печатается.

Меняется ТОЛЬКО последняя колонка, остальные байты строки и порядок строк — как были.

    python3 -I profile_surface.py [путь к pmk.metal.profile.csv] [--check]
    --check — ничего не пишет, печатает проверку массы, нераспознанные строки и образцы.
"""
