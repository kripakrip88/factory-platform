"""Пометка «какому режиму служит налог» (шаг 58).

ПОЧЕМУ ПОМЕТКА, А НЕ XMLID. Налог «НДС 22% (продажа)» заведён руками и стоит
у всех 753 товаров. Привяжи к нему xmlid этого модуля — и при удалении
pmk_org Odoo попробует удалить «свои» записи, в том числе этот налог.
Пометка — просто колонка: модуль удалят, колонка уйдёт, налоги останутся.
"""

from odoo import fields, models

from ..tools.regime import REGIMES


class AccountTax(models.Model):
    _inherit = "account.tax"

    pmk_regime = fields.Selection(
        REGIMES, "Режим ПМК", index=True, copy=False,
        help="Какой налоговый режим «Наших организаций» ставит этот налог в "
             "строки счёта покупателю. У налога продаж компании — не больше "
             "одного налога на режим.")
