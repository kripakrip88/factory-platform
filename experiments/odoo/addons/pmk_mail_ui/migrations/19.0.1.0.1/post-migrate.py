# -*- coding: utf-8 -*-
"""Письма на zakaz@ больше не создают лиды сами.

Решение Антона 28.09.2026: «менеджер сам переводит заявку с почты в лид и
сделку, нужно просто отключить автоматическое создание лидов с почты
zakaz@pmkpark.ru». Лид рождается кнопкой «Создать лида» в разделе «Почта».

ЧТО БЫЛО. 20.09.2026 на ящик zakaz@ появился адрес-приёмник (mail.alias)
«zakaz» с моделью crm.lead. Сервер входящей почты zakaz@ забирает письма, и
каждое письмо, не ставшее ответом на наше, по этому приёмнику становилось
лидом. Так 20-22.09 завелись лиды 3-11: ответы поставщиков на рассылку
прайсов, сбор средств, реклама. Все в архиве.

ЧТО ДЕЛАЕМ. Снимаем имя у приёмника: без имени он не совпадает ни с одним
адресом. Запись остаётся — вернуть = вписать имя «zakaz» обратно.

ЧТО ОСТАЁТСЯ КАК БЫЛО.
• Ответы на письма, отправленные из системы (запросы цен, КП), по-прежнему
  подшиваются к своим документам: это маршрут по заголовку References, до
  приёмников он не доходит.
• Письмо, которое некуда положить, Odoo пропускает и пишет в журнал
  («No possible route found»). Отправителю ничего не уходит: zakaz@ не
  адрес-ловушка (ловушка — catchall@), а автоответы и так погашены
  предохранителем models/mail_thread.py.
• Все письма ящика видны в разделе «Почта» — его синхронизация читает ящик
  сама, приёмники ей не нужны.

ПОЧЕМУ ORM, А НЕ SQL. Маршрутизация ищет приёмник по alias_full_name
(«zakaz@pmkpark.ru») — это хранимое вычисляемое поле. Правка одного
alias_name через SQL оставила бы полный адрес прежним, и лиды шли бы дальше.
"""
import logging

from odoo import api
from odoo.orm.utils import SUPERUSER_ID

_logger = logging.getLogger(__name__)


def migrate(cr, version):
    env = api.Environment(cr, SUPERUSER_ID, {})
    aliases = env["mail.alias"].search([
        ("alias_name", "=", "zakaz"),
        ("alias_model_id.model", "=", "crm.lead"),
    ])
    if not aliases:
        return
    _logger.info(
        "pmk_mail_ui: приёмник %s (id %s) больше не создаёт лиды — имя снято",
        aliases.mapped("alias_full_name"), aliases.ids,
    )
    aliases.write({"alias_name": False})
