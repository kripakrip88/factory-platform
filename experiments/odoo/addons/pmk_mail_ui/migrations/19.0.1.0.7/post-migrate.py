"""Имена вложений у писем, полученных до шага 41 (разбор удобства, В4).

С этой версии имена вложений пишутся в письмо при синхронизации — из
описания письма (BODYSTRUCTURE), которое модуль почты и так читает. У писем,
полученных раньше, имён нет: на 05.10.2026 вложения есть у 2 146 писем,
строки вложений заведены у 37 (их открывали).

1. Письма, которые открывали: имена — из уже заведённых строк вложений, без
   захода на почтовый сервер.
2. Остальные письма с вложениями, кроме Спама и Корзины (≈2 094 на
   05.10.2026): состав помечается «не прочитан» (structure_state='unknown'),
   и штатный крон «Mail Client: Describe Older Messages» прочитает только
   описание заново — 200 писем на папку раз в 15 минут, «Входящие» pmkpark@
   (≈1 343) — за ≈1 ч 45 мин. Файлы не качаются, отметка «прочитано» на
   mail.ru не меняется (EXAMINE и UID FETCH BODYSTRUCTURE — только чтение).
   Пока письмо не дочитано, его открытие прочитает состав само (лишний
   заход в ящик при открытии, ≈1–2 с) — так модуль почты делал и раньше для
   писем без состава.

Повторный запуск безвреден: письмам с именами ничего не делается.
Числа — в журнале сервера.
"""
import logging

from odoo import api
from odoo.orm.utils import SUPERUSER_ID

_logger = logging.getLogger(__name__)


def migrate(cr, version):
    if not version:
        return
    env = api.Environment(cr, SUPERUSER_ID, {})
    Message = env["mail.client.message"]
    named = Message._pmk_names_from_rows()
    queued = Message._pmk_queue_name_backfill()
    _logger.info(
        "pmk_mail_ui 19.0.1.0.7: имена вложений из строк — %s писем; "
        "поставлено в дочитку описания (крон Describe Older Messages) — %s писем.",
        named, queued)
