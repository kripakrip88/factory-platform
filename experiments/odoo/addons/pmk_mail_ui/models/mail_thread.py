# -*- coding: utf-8 -*-
"""Завод не отвечает автоматически на входящие письма.

ЧТО ПРОИСХОДИЛО. Ящик zakaz@pmkpark.ru объявлен адресом-ловушкой: на него
приходят ответы на письма, отправленные из системы, и Odoo подшивает их к
нужному документу по заголовку References. Но письмо, которое ловушке не
принадлежит — прислано человеком напрямую, — маршрутизировать некуда, и ядро
в этом случае ОТВЕЧАЕТ отправителю (mail_thread.py, ветка «Recipients contain
catchall and unroutable emails -> bounce», шаблон mail.mail_bounce_catchall).

20.09.2026 ящик первый раз забрал накопленную почту, и система заготовила 113
таких ответов — каждому, кто присылал спам: сбор средств, рассылки по юрлицам,
выкуп неликвида. Письма отменены вручную и наружу не ушли.

ПОЧЕМУ ЭТО НАДО ГАСИТЬ, А НЕ ПОЧИНИТЬ ТЕКСТ. Опасен здесь не спамер, а клиент.
Штатная отбойка написана ПО-АНГЛИЙСКИ, а фраза «свяжитесь с нами по адресу»
обрывается на пустом месте, потому что запасной адрес не задан. Человек,
написавший на завод по делу, получал бы с адреса завода английскую отписку с
дырой вместо адреса. Такого письма лучше не отправлять вовсе: молчание честнее
испорченного ответа.

ПОЧЕМУ НЕ УБРАТЬ ЛОВУШКУ ЦЕЛИКОМ. Тогда перестанут подшиваться ответы
поставщиков на наши запросы цен — ровно то, ради чего ящик и заведён. Ловушка
остаётся, гасится только исходящий автоответ: письмо, которое некуда положить,
просто не обрабатывается, и ядро само пишет об этом в журнал.

ЧТО БУДЕТ ДАЛЬШЕ. Целевой сценарий — письмо рождает ЛИД, а не отказ. Когда он
будет собран, отбойке просто неоткуда взяться: маршрут найдётся всегда. До тех
пор здесь стоит предохранитель.

Решение владельца 21.09.2026: «автоответы нам вообще не нужны».
"""
import logging

from odoo import models

_logger = logging.getLogger(__name__)


class MailThread(models.AbstractModel):
    _inherit = "mail.thread"

    # Декоратора @api.model здесь нет намеренно: в ядре у этого метода его тоже
    # нет (в отличие от соседнего _routing_handle_bounce). Сигнатуру переопределения
    # держим один в один с ядром — иначе расхождение вылезет при обновлении Odoo.
    def _routing_create_bounce_email(self, email_from, body_html, message, **mail_values):
        """Не отвечать отправителю. Ничего не создаём и не отправляем.

        Ядро вызывает этот метод из трёх мест (письмо на ловушку без маршрута,
        письмо на алиас без прав, письмо на алиас с закрытой записью) и НИ В
        ОДНОМ не использует возвращённое значение — поэтому пустой ответ
        безопасен. Проверено по mail_thread.py: вызовы в строках 1083, 1278 и
        1328 стоят отдельными выражениями.

        Пишем в журнал на уровне INFO, а не молчим: когда письмо от настоящего
        клиента не найдёт маршрута, по этой строке будет видно, кому система
        НЕ ответила, и станет понятно, что пора доделывать сценарий с лидом.
        """
        subject = (message.get("Subject") or "").strip() if message else ""
        _logger.info(
            "Автоответ подавлен (предохранитель pmk_mail_ui): отправитель %s, тема %r",
            email_from, subject[:120],
        )
        return self.env["mail.mail"]
