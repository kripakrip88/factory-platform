def kg_per_mm(diameter):
    return math.pi * diameter * diameter / 4.0 * STEEL_DENSITY


def check(bolt_type, d):
    """Текст ошибки или пусто: тип и диаметр по таблице 1."""
    spec = TYPES.get(bolt_type)
    if not spec:
        return "Тип %s в ГОСТ 24379.1 не описан" % bolt_type
    if d not in spec["diameters"]:
        return "Тип %s делают М%s–М%s" % (bolt_type, spec["diameters"][0], spec["diameters"][-1])
    return ""


def blank_mm(bolt_type, d, length):
    """Длина заготовки шпильки, мм — по правилу цеха (2d на гиб)."""
    s = SIZES[d]
    if bolt_type == "1.1":
        return length + s["l"] - 2 * d
    if bolt_type == "1.2":
        return length + s["l2"] - 2 * d + (math.hypot(s["l1"], s["l3"]) - s["l1"])
    return float(length)


def stud_kg(bolt_type, d, length):
    """Металл шпильки по заготовке, кг (тело — d1)."""
    return blank_mm(bolt_type, d, length) * kg_per_mm(SIZES[d]["d1"])


def table_mass(bolt_type, d, length):
    """Масса болта в сборе по приложению А или None (длины нет в ряду ГОСТ)."""
    table = {"1": A1, "2": A2, "5": A3}[bolt_type.split(".")[0]]
    return table.get((d, int(length)))


def standard_lengths(bolt_type, d):
    table = {"1": A1, "2": A2, "5": A3}[bolt_type.split(".")[0]]
    return sorted(length for (dd, length) in table if dd == d)


def mass(bolt_type, d, length):
    """Масса в сборе, кг: по ГОСТ; длина не из ряда — по прямой между соседними
    длинами ряда (масса линейна по длине), за краем ряда — по двум крайним.
    Правило цеха «2d на гиб» — для металла в себестоимости, не для массы:
    заготовка цеха короче той, что заложена в теоретических массах ГОСТ."""
    found = table_mass(bolt_type, d, length)
    if found is not None:
        return found
    table = {"1": A1, "2": A2, "5": A3}[bolt_type.split(".")[0]]
    points = standard_lengths(bolt_type, d)
    if len(points) >= 2:
        below = [x for x in points if x < length]
        above = [x for x in points if x > length]
        a, b = (below[-1], above[0]) if below and above else ((points[0], points[1]) if not below
                                                              else (points[-2], points[-1]))
        ma, mb = table[(d, a)], table[(d, b)]
        return round(ma + (mb - ma) * (length - a) / (b - a), 2)
    spec, s = TYPES[bolt_type], SIZES[d]
    total = stud_kg(bolt_type, d, length) + spec["nuts"] * NUT_KG[d] + s["w"]
    if spec["plate"]:
        total += s["plate"][2]
    return round(total, 3)


