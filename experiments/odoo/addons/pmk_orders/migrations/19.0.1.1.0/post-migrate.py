# -*- coding: utf-8 -*-
"""Шаг З-9: «Отправлен» — когда (pmk_sent_date) у уже отправленных счетов;
цена строк-изделий — «ручная» для ядра.

1. Новое поле pmk_sent_date ставится при каждой отметке «Отправлен». У счетов,
выставленных до шага (З-2: «Выставлен, ждём оплату» сразу при «КП
отправлено»), его нет — а по нему кнопка «Счёт» в расчёте решает, хранить ли
содержание отменённого счёта редакцией (он уже уходил клиенту). Берём дату
счёта: отправленные и в работе — уходили клиенту; отменённые — только если
из них уже были редакции (прочие отменённые могли не уходить никогда —
оставляем пусто). Снимки (прежние редакции) — их дата.

Согласование (pmk_approval) у старых счетов — «Не согласовывался» (значение
по умолчанию поля): пометка «Отправлен без согласования» у них правдива —
до шага согласования не было. Статус словами (pmk_status) ядро считает
само при добавлении колонки. На 09.10.2026 на боевой — один счёт, в работе.

2. Строки-изделия (pmk_from_spec) заводились с technical_price_unit =
price_unit (ядро ставит так при создании). Для ядра такая цена — «из
товара»: смена одного количества (черновик идёт за расчётом) пересчитала
бы её в цену товара «Изготовление металлоконструкций» — 0 ₽. technical = 0
делает цену ручной, как у новых строк (sale_order._pmk_line_vals). Строки
счетов в работе тоже: цена у них не меняется, а правило одно. Сумма и цена
не меняются. На боевой 09.10.2026 — одна такая строка (id 19).

Повторный прогон ничего не меняет (только пустые / ещё не нулевые).
"""
import logging

_logger = logging.getLogger(__name__)


def migrate(cr, version):
    if not version:
        return
    cr.execute("""
        UPDATE sale_order so
           SET pmk_sent_date = so.date_order
         WHERE so.pmk_sent_date IS NULL
           AND (so.state IN ('sent', 'sale')
                OR so.pmk_is_revision
                OR EXISTS (SELECT 1 FROM sale_order r WHERE r.pmk_revision_of_id = so.id))
    """)
    _logger.info("pmk_orders 19.0.1.1.0: дата «Отправлен» проставлена у %s счетов", cr.rowcount)
    cr.execute("""
        UPDATE sale_order_line
           SET technical_price_unit = 0
         WHERE pmk_from_spec
           AND COALESCE(technical_price_unit, 0) <> 0
    """)
    _logger.info("pmk_orders 19.0.1.1.0: цена строк-изделий — ручная у %s строк", cr.rowcount)
