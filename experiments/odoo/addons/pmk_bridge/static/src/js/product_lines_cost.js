/**
 * Стоимость закупки в составе изделия.
 *
 * Шаблон состава расширен отдельным файлом (product_lines_cost.xml), и ему
 * нужен метод costOf. Добавляем его патчем, а не наследником класса: виджет
 * зарегистрирован в реестре полей под именем pmk_product_lines, и подмена
 * класса означала бы вторую регистрацию — кто победит, зависело бы от порядка
 * загрузки файлов.
 */

import { patch } from "@web/core/utils/patch";
import { ProductLinesRenderer } from "@pmk_calc/js/product_lines_field";

// Почему у строки нет суммы — словом вместо прочерка (разбор UX, шаг 32).
// Прочерк у детали без цены читался как «ещё не посчитано», а это сигнал:
// позиции нет в прайсах — значит в городе её нет, металл в итоге занижен.
// Цвет повторён словом; подсказка объясняет, что это значит. Ничего не
// блокирует. Состояния — price_state из models/spec_cost.py.
const COST_SIGNALS = {
    no_price: {
        label: "нет в прайсах",
        tone: "warn",
        title: "Позиции нет в прайсах — в городе её нет. Металл в итоге занижен",
    },
    no_link: {
        label: "нет в прайсах",
        tone: "warn",
        title: "Позиция справочника не связана с номенклатурой, цены по ней нет. Металл в итоге занижен",
    },
    no_mass: {
        label: "нет массы",
        tone: "warn",
        title: "У позиции не задана масса — цену за килограмм не пересчитать. Металл в итоге занижен",
    },
    not_material: {
        label: "услуга",
        tone: "muted",
        title: "Работа подрядчика, а не материал: по весу не считается",
    },
};

patch(ProductLinesRenderer.prototype, {
    /**
     * «Цена за шт» правится прямо в строке изделия, как количество (разбор
     * UX, шаг 56; Антон 07.10: «Почему нельзя изменить цену за штуку в общем
     * списке…»). Поле — обычное ручное (price_customer_unit, без наценки и
     * без вычисления), «Сумма» и итоги расчёта пересчитываются onchange, как
     * из окна изделия. Механизм — pmk_calc, product_lines_field.js.
     */
    pmkInlineFieldNames() {
        return [...super.pmkInlineFieldNames(), "price_customer_unit"];
    },

    /** Сигнал вместо суммы: {label, tone, title} или null, если сумма есть. */
    costSignal(line) {
        return COST_SIGNALS[line.data.price_state] || null;
    },

    /**
     * Сумма закупки строки: столько стоит металл, который придётся купить
     * под эту деталь во всём изделии.
     *
     * Прочерк вместо нуля, когда суммы нет (позиция не выбрана или цена
     * нулевая). Ноль в денежной колонке читается как «бесплатно» и проходит
     * мимо глаз. Строки без цены в прайсе показывает costSignal — словом.
     */
    costOf(line) {
        const state = line.data.price_state;
        if (state && state !== "ok") {
            return "—";
        }
        const value = line.data.cost_fact_total || 0;
        if (!value) {
            return "—";
        }
        // Разряды пробелами и запятая в дробной части — как в остальных
        // числах документа.
        return value.toLocaleString("ru-RU", {
            minimumFractionDigits: 2,
            maximumFractionDigits: 2,
        });
    },
});
