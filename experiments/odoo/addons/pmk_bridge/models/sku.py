# -*- coding: utf-8 -*-
"""Генератор артикулов (default_code) для переноса справочника pmk_calc
в номенклатуру Odoo.

Зачем вообще артикул. Цена поставщика в Odoo живёт в product.supplierinfo и
требует товар — положить её «на строку справочника» некуда. Значит на каждую
строку сортамента заводится карточка товара, и её надо чем-то опознавать при
следующей загрузке прайса. Имя для этого не годится: «Уголок равнополочный
63x63x5 ГОСТ 8509-93» переводится, переименовывается и в каждом прайсе пишется
по-своему. Артикул — единственный стабильный ключ, поэтому он:

  * латинский — ноль не-ASCII символов. Кириллица в артикуле ломается при
    выгрузке в 1С, в CSV без BOM и в URL: один и тот же «Уголок» приезжает то
    как «Уголок», то как «Óãîëîê», и сопоставление рассыпается;
  * говорящий — по UGR-63x63x5 человек читает позицию без справочника;
  * без контрольного хвоста — решение владельца. Хеш/чек-сумма делает артикул
    нечитаемым, а от опечаток всё равно не спасает: опечатка даёт валидный
    артикул другой позиции.

Здесь только чистые функции: строка справочника → строка артикула. Никакого
ORM, никаких запросов. Так их можно прогнать по CSV и по живой базе, не
поднимая Odoo, и так их проверяют тесты.
"""


# --- Транслитерация ------------------------------------------------------

# Регистр СОХРАНЯЕТСЯ. Это не украшательство: на нём держатся утверждённые
# артикулы. «Ду15x2.5» → «Du15x2.5» (Д заглавная, у строчная), «d12» остаётся
# «d12», «S24» остаётся «S24». Если всё поднять в верхний регистр, получится
# VGP-DU15X2.5 — уже не то, что утверждено.
_TRANSLIT_UPPER = {
    "А": "A", "Б": "B", "В": "V", "Г": "G", "Д": "D", "Е": "E", "Ё": "E",
    "Ж": "ZH", "З": "Z", "И": "I", "Й": "Y", "К": "K", "Л": "L", "М": "M",
    "Н": "N", "О": "O", "П": "P", "Р": "R", "С": "S", "Т": "T", "У": "U",
    "Ф": "F", "Х": "H", "Ц": "TS", "Ч": "CH", "Ш": "SH", "Щ": "SCH",
    "Ъ": "", "Ы": "Y", "Ь": "", "Э": "E", "Ю": "YU", "Я": "YA",
}
_TRANSLIT = dict(_TRANSLIT_UPPER)
_TRANSLIT.update({k.lower(): v.lower() for k, v in _TRANSLIT_UPPER.items()})

# Токены, которые нельзя разбирать по буквам. Применяются ДО посимвольной
# замены. «ромб» по буквам дал бы «romb» — а утверждено RHM.
_TRANSLIT_TOKENS = {
    "ромб": "RHM",
}

# Разделители размеров. Разные у проката и у метизов — это не догадка, а
# факт из данных: в 665 строках проката стоит ЛАТИНСКАЯ «x» (U+0078) и ни
# одной кириллической «х» (U+0445); в 25 строках метизов — ровно наоборот,
# знак умножения «×» (U+00D7) в 15 строках и ни одной латинской «x».
# Отсюда два разных парсера: каждый проверяет, что ему отдали строку из его
# справочника, и падает, если перепутали. Молча съесть чужой разделитель
# нельзя — получится артикул-двойник, который вылезет уже на ценах.
PROFILE_SEP = "x"          # U+0078, латинская
FASTENER_SEP = "×"    # U+00D7, знак умножения
CYRILLIC_X = "х"      # кириллическая «х» — в проката её быть не должно
CYRILLIC_M = "М"      # «М» из «М8×20»


class SkuError(ValueError):
    """Строку справочника не удалось разобрать.

    Отдельный класс, чтобы загрузчик мог отличить «не тот справочник / битая
    строка» от любой другой ошибки и остановиться, а не завести карточку с
    мусорным артикулом.
    """


def translit(text):
    """Кириллица → латиница с сохранением регистра.

    Неизвестный не-ASCII символ — это ошибка, а не повод подставить «?».
    Тихая подмена дала бы два разных сортамента с одним артикулом.
    """
    out = []
    rest = text
    while rest:
        for token, repl in _TRANSLIT_TOKENS.items():
            if rest.startswith(token):
                out.append(repl)
                rest = rest[len(token):]
                break
        else:
            ch = rest[0]
            rest = rest[1:]
            if ord(ch) < 128:
                out.append(ch)
            elif ch in _TRANSLIT:
                out.append(_TRANSLIT[ch])
            else:
                raise SkuError(
                    "нечего подставить вместо %r (U+%04X) в %r" % (ch, ord(ch), text))
    return "".join(out)


def _assert_ascii(sku, source):
    """Последний рубеж. Транслитерация могла пропустить символ, которого нет в
    таблице, — артикул с кириллицей не должен уехать в базу ни при каких
    обстоятельствах."""
    bad = [c for c in sku if ord(c) > 127]
    if bad:
        raise SkuError("в артикуле %r остались не-ASCII %r (из %r)" % (sku, bad, source))
    return sku


# --- Прокат --------------------------------------------------------------

# Вид проката → префикс. Ключи совпадают с полем profile_type справочника
# pmk.metal.profile — все 12 видов, что там есть.
PROFILE_PREFIX = {
    "Арматура": "ARM",
    "Двутавр": "DVT",
    "Швеллер": "SHV",
    "Уголок равнополочный": "UGR",
    "Уголок неравнополочный": "UGN",
    "Круг": "KRG",
    "Квадрат": "KVD",
    "Шестигранник": "SHG",
    "Труба круглая": "TRK",
    "Труба профильная квадратная": "TPK",
    "Труба профильная прямоугольная": "TPP",
    "Труба ВГП": "VGP",
}

# Бесшовная труба отделена суффиксом, а не отдельным префиксом: решение
# владельца — это две разные карточки (разные ГОСТы 10704-91 и 8732-78,
# разные цены), но один вид проката. TRK-89x4 и TRK-89x4-BS стоят рядом в
# любом списке, отсортированном по артикулу, — так их и сравнивают.
SEAMLESS_MARK = " бесш"
SEAMLESS_SUFFIX = "BS"


def profile_sku(profile_type, size_label):
    """Строка pmk.metal.profile → артикул.

    Примеры: («Двутавр», «20Ш1») → DVT-20SH1; («Труба ВГП», «Ду15x2.5») →
    VGP-Du15x2.5; («Труба круглая», «89x4 бесш») → TRK-89x4-BS.
    """
    prefix = PROFILE_PREFIX.get(profile_type)
    if not prefix:
        raise SkuError("неизвестный вид проката %r" % (profile_type,))

    size = (size_label or "").strip()
    if not size:
        raise SkuError("пустой типоразмер у %r" % (profile_type,))

    suffix = ""
    if size.endswith(SEAMLESS_MARK):
        size = size[: -len(SEAMLESS_MARK)].strip()
        suffix = "-" + SEAMLESS_SUFFIX

    # Парсер проката: свой разделитель и только свой.
    if FASTENER_SEP in size:
        raise SkuError(
            "в типоразмере проката %r знак «×» — это разделитель метизов, "
            "строка попала не в тот парсер" % (size_label,))
    if CYRILLIC_X in size:
        raise SkuError(
            "в типоразмере проката %r кириллическая «х» вместо латинской «x» — "
            "визуально не отличить, артикул получился бы двойником" % (size_label,))

    # Размеры разбираются по «x» и собираются обратно через него же. Разбор
    # здесь не декоративный: он проверяет, что между разделителями что-то есть
    # («20xx3» и «20x» до базы не доедут).
    parts = size.split(PROFILE_SEP)
    for part in parts:
        if not part:
            raise SkuError("пустая часть размера в %r" % (size_label,))
    body = PROFILE_SEP.join(translit(p) for p in parts)

    return _assert_ascii("%s-%s%s" % (prefix, body, suffix), size_label)


# --- Лист ----------------------------------------------------------------

# Лист считаем ШТУКАМИ листа определённого размера (решение владельца), а
# габарит 1500x3000 / 1500x6000 / 1000x4000 — характеристика варианта. Поэтому
# в артикуле карточки габарита НЕТ: карточка одна, вариантов у неё три.
SHEET_PREFIX = {
    "Гладкий": "LST-GL",
    "Рифлёный": "LST-RF",
    "Просечно-вытяжной": "LST-PV",
    "Оцинкованный тонколистовой": "LST-ZN",
}

# У ПВЛ обозначение «406» само по себе содержит и толщину (4 мм), и номер
# просечки (06). Брать толщину отдельно нельзя: 506, 508 и 510 — три разных
# листа одной толщины 5 мм, по толщине они слились бы в один артикул.
SHEET_LABEL_IS_SIZE = {"Просечно-вытяжной"}

# ГОСТ 8568-77 знает два рифления, ромбическое и чечевичное. В справочнике
# сейчас только ромб — все 8 строк. Токен, одинаковый у всех строк, ничего не
# различает, поэтому утверждённый артикул рифлёного листа — LST-RF-4, без
# хвоста. Появится чечевица — её рифление в артикул попадёт, а ромбовые
# артикулы останутся прежними: перенумеровывать заведённые карточки нельзя,
# на них уже висят цены поставщиков и строки заказов.
SHEET_DEFAULT_PATTERN = "ромб"


def _num(value):
    """Число в артикул без хвоста нулей: 4.0 → «4», 0.50 → «0.5».

    Толщина приходит из Float-поля Odoo и из CSV в разном виде («1» и «1.0» —
    это один и тот же лист). Без нормализации одна и та же позиция получила бы
    два артикула при двух разных загрузках.
    """
    try:
        return "%g" % float(value)
    except (TypeError, ValueError):
        raise SkuError("не число: %r" % (value,))


def sheet_sku(sheet_type, thickness_mm, size_label=None):
    """Строка pmk.metal.sheet → артикул.

    Примеры: («Гладкий», 3) → LST-GL-3; («Оцинкованный тонколистовой», 0.5) →
    LST-ZN-0.5; («Просечно-вытяжной», 4, «406») → LST-PV-406;
    («Рифлёный», 4, «ромб») → LST-RF-4.
    """
    prefix = SHEET_PREFIX.get(sheet_type)
    if not prefix:
        raise SkuError("неизвестный вид листа %r" % (sheet_type,))

    label = (size_label or "").strip()

    if sheet_type in SHEET_LABEL_IS_SIZE:
        if not label:
            raise SkuError("у листа %r пустое обозначение, толщины для артикула мало"
                           % (sheet_type,))
        body = translit(label)
    else:
        body = _num(thickness_mm)
        if label and label != SHEET_DEFAULT_PATTERN:
            body += "-" + translit(label)

    return _assert_ascii("%s-%s" % (prefix, body), "%s %s %s" % (sheet_type, thickness_mm, label))


# --- Метизы --------------------------------------------------------------

# Префикс по виду метиза — трёхбуквенное сокращение английского ключа поля
# fastener_type (bolt/nut/washer/anchor/screw/other). Ключ уже латинский и
# уже лежит в данных, так что выдумывать нечего.
FASTENER_PREFIX = "MTZ"
FASTENER_KIND = {
    "bolt": "BLT",
    "nut": "NUT",
    "washer": "WSH",
    "anchor": "ANC",
    "screw": "SCR",
    "other": "OTH",
}


def fastener_sku(fastener_type, size_label):
    """Строка pmk.metal.fastener → артикул.

    Примеры: («bolt», «М8×20») → MTZ-BLT-M8x20; («nut», «М8») → MTZ-NUT-M8;
    («screw», «4.8×35») → MTZ-SCR-4.8x35.

    Парсер отдельный от проката: здесь разделитель «×» (U+00D7), а «М» —
    кириллическая (U+041C). Латинской «x» в этом справочнике нет ни в одной
    из 25 строк, поэтому её появление означает, что строку взяли из проката.
    """
    kind = FASTENER_KIND.get(fastener_type)
    if not kind:
        raise SkuError("неизвестный вид метиза %r" % (fastener_type,))

    size = (size_label or "").strip()
    if not size:
        raise SkuError("пустой типоразмер у метиза %r" % (fastener_type,))

    if PROFILE_SEP in size:
        raise SkuError(
            "в типоразмере метиза %r латинская «x» — это разделитель проката, "
            "строка попала не в тот парсер" % (size_label,))

    # «М8×20» → [«М8», «20»]. Резьба и длина разбираются по отдельности, чтобы
    # «М8×» или «×20» не превратились в артикул с висящим дефисом.
    parts = size.split(FASTENER_SEP)
    for part in parts:
        if not part.strip():
            raise SkuError("пустая часть размера в %r" % (size_label,))

    # Кириллическая «М» резьбы переводится в латинскую тем же правилом
    # М→M — отдельной ветки не нужно, но проверить наличие стоит: метиз без
    # обозначения резьбы бывает (саморез 4.8×35), а «M» латинская в исходнике
    # означала бы, что справочник уже кто-то правил руками вперемешку.
    if "M" in size and CYRILLIC_M not in size:
        raise SkuError(
            "в типоразмере метиза %r латинская «M» вместо кириллической «М» — "
            "в справочнике так быть не должно" % (size_label,))

    body = PROFILE_SEP.join(translit(p.strip()) for p in parts)
    return _assert_ascii("%s-%s-%s" % (FASTENER_PREFIX, kind, body), size_label)


# --- ЛКП -----------------------------------------------------------------

# Покрытия — товары в килограммах (решение владельца). Наименования у них
# сплошь кириллические («Цинконаполненная грунтовка» — 25 разных букв), и
# транслитерация дала бы нечитаемую кашу LKP-TSINKONAPOLNENNAYA-GRUNTOVKA.
# Зато XML-id строки уже латинский, короткий и говорящий — его и берём.
PAINT_PREFIX = "LKP"
PAINT_XMLID_PREFIX = "paint_"


def paint_sku(xml_id):
    """Строка pmk.paint.coating → артикул.

    Пример: «paint_gf021» → LKP-GF021, «paint_zinc_hot» → LKP-ZINC-HOT.
    Принимает как короткий id, так и полный «pmk_calc.paint_gf021».
    """
    ident = (xml_id or "").strip()
    if "." in ident:
        ident = ident.split(".", 1)[1]
    if not ident.startswith(PAINT_XMLID_PREFIX):
        raise SkuError("XML-id покрытия %r не начинается с %r"
                       % (xml_id, PAINT_XMLID_PREFIX))
    tail = ident[len(PAINT_XMLID_PREFIX):]
    if not tail:
        raise SkuError("у покрытия %r пустой XML-id после префикса" % (xml_id,))
    return _assert_ascii("%s-%s" % (PAINT_PREFIX, tail.upper().replace("_", "-")), xml_id)


# --- Варианты ------------------------------------------------------------

def grade_code(grade_name):
    """Марка стали → хвост артикула варианта. «09Г2С» → 09G2S, «Ст3сп» → St3sp."""
    name = (grade_name or "").strip()
    if not name:
        raise SkuError("пустая марка стали")
    # Пробелы и точки внутри марки в артикуле не нужны: они ломают выгрузки
    # и поиск. В текущих восьми марках их нет, но прайсы приносят «Ст3 сп».
    compact = "".join(name.split()).replace(".", "")
    return _assert_ascii(translit(compact), grade_name)


def variant_sku(base_sku, *suffixes):
    """Артикул варианта: артикул карточки + характеристики через дефис.

    Марка стали — характеристика с dynamic-вариантами, поэтому на складе
    лежит не «Двутавр 20Б1», а «Двутавр 20Б1 из 09Г2С»: DVT-20B1-09G2S.
    Порядок хвостов фиксирован вызывающим кодом — переставишь местами и
    получишь второй артикул на тот же вариант.
    """
    parts = [base_sku]
    for suffix in suffixes:
        suffix = (suffix or "").strip()
        if not suffix:
            raise SkuError("пустая характеристика в варианте %r" % (base_sku,))
        parts.append(suffix)
    return _assert_ascii("-".join(parts), base_sku)


# --- Диспетчер -----------------------------------------------------------

def sku_for_row(model, row):
    """Строка любого из четырёх справочников → артикул.

    `model` — техническое имя справочника, `row` — dict с полями строки (как
    из CSV, так и из read() Odoo). Одна точка входа нужна загрузчику: он идёт
    по четырём справочникам подряд и не должен помнить, у кого какой парсер.
    """
    if model == "pmk.metal.profile":
        return profile_sku(row["profile_type"], row["size_label"])
    if model == "pmk.metal.sheet":
        return sheet_sku(row["sheet_type"], row["thickness_mm"], row.get("size_label"))
    if model == "pmk.metal.fastener":
        return fastener_sku(row["fastener_type"], row["size_label"])
    if model == "pmk.paint.coating":
        return paint_sku(row["id"])
    raise SkuError("нет генератора артикулов для справочника %r" % (model,))
