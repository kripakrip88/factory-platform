"""Признак «поставщик» для карточки контрагента (разбор UX, шаг 28).

ЗАЧЕМ. С шага 28 карточка показывает клиенту и поставщику разное: «Продажи»
или «Закупку» (pmk_purchase), кнопку «Расчёты» всегда или только при
расчётах (pmk_deal). Каждый вид решал «поставщик ли это» своим выражением, и
выражения разошлись: блоки знали «Поставщика прайсов», а кнопка — нет (она в
pmk_deal, который от закупок не зависит). Теперь все смотрят на это поле.

ПОЧЕМУ ВЫЧИСЛЯЕМОЕ, А НЕ supplier_rank. Первая версия шага ставила
supplier_rank = 1 каждому, кому отметили «Поставщик прайсов», а снятый флажок
ранг не сбрасывал. Клиент, отмеченный по ошибке, навсегда уходил из «Продажи →
Клиенты» (фильтр требует supplier_rank = 0): ранг в интерфейсе нигде не
правится. Признак ничего не пишет в базу: снял флажок — карточка снова
клиентская.

ПО КОММЕРЧЕСКОМУ ПАРТНЁРУ. Контактное лицо поставщика — сторона поставщика: у
него «Закупка», а не «Продажи», и нет «Расчётов 0». Ранг и «Поставщик прайсов»
стоят на компании и контактному лицу не передаются (общими полями компании
они не являются), поэтому смотрим и на самого контрагента, и на его компанию.

Здесь — штатная часть (supplier_rank: заказы и счета поставщика). «Поставщика
прайсов» дописывает pmk_purchase (models/res_partner.py). Мост — общий низ:
от него зависят и pmk_deal, и pmk_purchase.
"""

from odoo import api, fields, models


class ResPartnerSupplierSign(models.Model):
    _inherit = "res.partner"

    pmk_is_supplier = fields.Boolean(
        "Поставщик", compute="_compute_pmk_is_supplier",
        help="Контрагент или его компания — поставщик: по штатному признаку "
             "(заказы и счета поставщика) или по реестру прайсов.")

    @api.depends("supplier_rank", "commercial_partner_id.supplier_rank")
    def _compute_pmk_is_supplier(self):
        for partner in self:
            partner.pmk_is_supplier = bool(
                partner.supplier_rank or partner.commercial_partner_id.supplier_rank)
