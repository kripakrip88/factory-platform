# Марка, которой заливка карточек метит единственный вариант (SEED_GRADE в
# scripts/load_products.py). При столкновении цен разных марок цена этой марки
# имеет преимущество: именно её купят.
BASE_GRADE = "Ст3сп"


def normalise_grade(raw):
    """Привести марку прайса к ключу.

    Грабли из живого файла: «О9Г2С-12» начинается с КИРИЛЛИЧЕСКОЙ «О», а не с
    нуля — 18 строк листа. Глазом не отличить, а ключ разъезжается, и лист
    09Г2С молча уходит в «марка не заведена».
    """
    s = (raw or "").upper().replace("Ё", "Е")          # Ё -> Е
    s = s.replace("О", "0") if re.match(r"^О\d", s) else s  # О9Г2С -> 09Г2С
    s = re.sub(r"[\s\\/\.\-\(\)]", "", s)
    s = re.sub(r"(2СОРТ|НМЗ)$", "", s)
    return s


def map_grade(raw):
    return GRADE_MAP.get(normalise_grade(raw))


def grade_from_vendor_name(name):
    """Марка из названия строки прайса «профиль размер марка» (vendor_name).

    Для старых цен проката (№313): до 24.10.2026 они лежали на шаблоне, а марка
    осталась только в названии. Хвост в 1–3 слова, первый опознанный, но только
    с буквой: «Круг 20» — размер, а не сталь 20 («Ст 20» — сталь).
    """
    words = (name or "").split()
    for k in (1, 2, 3):
        if len(words) <= k:
            break
        tail = " ".join(words[-k:])
        if re.search(r"[^\d\s.,]", tail) and re.search(r"[A-Za-zА-Яа-яЁё]", tail):
            grade = map_grade(tail)
            if grade:
                return grade
    return None


# Взаимозаменяемые марки (Антон 25.10.2026: Ст3сп и Ст3пс — «это взаимозаменяемые
# стали»): строка с одной из них берёт самую дешёвую цену любой. С345 = 09Г2С —
# уже в GRADE_MAP (написание прайса и ячейки «Марка» → 09Г2С).
# 08кп и 08пс — тонкий лист, Металлсервис пишет «08кп/пс» (на выбор поставщика), а в счёте
# ставит «Ст08пс» (26.10.2026): цена одна, как у Ст3сп/Ст3пс.
GRADE_EQUIV = (frozenset(("Ст3сп", "Ст3пс")), frozenset(("08кп", "08пс")))


def grade_family(grade):
    """Марки, чья цена годится строке с маркой grade (сама марка — всегда)."""
    for family in GRADE_EQUIV:
        if grade in family:
            return family
    return frozenset((grade,))
