/**
 * Лента документа справа на широком экране — разбор UX, шаг 49Б (10.10.2026):
 * правила без Odoo.
 *
 * Чистые функции без импортов Odoo — их гоняет node
 * (static/tests/chatter_aside_step49b.test.mjs). Использует chatter_inline.js.
 *
 * Замечание Антона (карточка «Рабочий компьютер», экран 2560×1440): лист до
 * 1800 px прижат влево, справа ~760 px пусто, «История» — под листом. Решение
 * 10.10: «давай попробуем, я проверю, если не понравится вернём» — от 2200 px
 * лента встаёт справа от листа штатным боковым режимом ядра (SIDE_CHATTER);
 * уже — внизу, как в шагах 30 и 49.
 *
 * ВЫКЛЮЧАТЕЛЬ «не понравилось»: ASIDE_MIN_WIDTH = Infinity. Тогда ядро
 * никогда не получает боковую раскладку, класса o-aside нет, правила раздела
 * «Шаг 49Б» в forms_nexus.scss не срабатывают — вид шага 49 целиком.
 */

/**
 * Ширина окна (CSS-точки), с которой лента — справа от листа. То же число —
 * $pmk-aside-from в forms_nexus.scss, раздел «Шаг 49Б» (тест сверяет).
 *
 * Почему 2200: лист 1800 + лента не уже 420 + отступ справа 16 = 2236; на
 * 2200–2235 лист ужимается не больше чем на 36 px (карточка ~1730 против
 * 1768) — меньше, чем дал бы любой порог ниже. 1920 и меньше — как было.
 * На 2560 (экран Антона): лист 1800, лента 720, справа 24 px.
 */
export const ASIDE_MIN_WIDTH = 2200;

/** Медиазапрос порога — совпадает с @media в SCSS (учёт полосы прокрутки и масштаба). */
export const ASIDE_MEDIA = `(min-width: ${ASIDE_MIN_WIDTH}px)`;

/** Окно не уже порога. Нет числа — не широкое. */
export function isWideViewport(width, min = ASIDE_MIN_WIDTH) {
    return Number.isFinite(width) && width >= min;
}

/**
 * Раскладка ленты: боковая ядра (SIDE_CHATTER) — только от порога, уже —
 * внизу (BOTTOM_CHATTER). Остальные раскладки ядра (вложение рядом — COMBO,
 * вложение в отдельном окне — EXTERNAL_*, без ленты — NONE) как есть.
 */
export function chatterLayout(coreLayout, wide) {
    return coreLayout === "SIDE_CHATTER" && !wide ? "BOTTOM_CHATTER" : coreLayout;
}

/**
 * Свёрнута ли история сейчас. Сбоку — всегда развёрнута: свёрнутая полоса
 * справа оставила бы пустую колонку. Выбор «свёрнуто» (по типу документа)
 * при этом сохраняется и снова действует, когда лента под листом.
 */
export function collapsedNow(collapsed, aside) {
    return Boolean(collapsed) && !aside;
}

/**
 * Пересчитывать ли состояние ленты сразу по смене медиазапроса порога.
 * Только когда окно стало широким (matches = true). При сужении раскладку
 * перекладывает рендерер ядра с задержкой 200 мс, а @media в SCSS гаснет
 * сразу — свёрнутая лента в этот миг стояла бы справа пустой полосой.
 * Состояние тогда ставит useEffect по смене isChatterAside.
 */
export function shouldApplyOnWidth(matches) {
    return matches === true;
}
