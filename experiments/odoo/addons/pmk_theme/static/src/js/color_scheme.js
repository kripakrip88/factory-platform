/**
 * Переключатель вида: тёмный кабинет / светлый цех.
 *
 * Зачем. Завод выходит в цех — лазерный участок, гибка, покраска, сварка. На
 * экране у станка, при дневном свете из ворот, тёмный интерфейс не читается:
 * там нужен белый фон. В кабинете удобнее тёмный. Поэтому переключатель, а не
 * замена одного вида другим.
 *
 * Где. В меню пользователя, рядом с «Мои настройки»: это единственное место,
 * которое человек ищет, когда хочет поменять что-то про себя. Отдельной кнопки
 * в шапке не делаем — шапка и так в две строки.
 *
 * Как. Переключаем атрибут на <html> И пишем куку. Атрибут даёт мгновенный
 * отклик без перезагрузки (вся палитра живёт на CSS-переменных), кука нужна,
 * чтобы сервер отдал тот же вид при следующем открытии — уже первым кадром,
 * без тёмного проблеска. Перезагружать страницу не надо: ни один вид не
 * зависит от того, какие файлы подключены, разница только в значениях
 * переменных.
 */

import { registry } from "@web/core/registry";
import { cookie } from "@web/core/browser/cookie";
import { _t } from "@web/core/l10n/translation";

const COOKIE = "pmk_color_scheme";

/** Текущий вид читаем с разметки, а не из куки: разметку поставил сервер, и
 *  именно она сейчас на экране. Кука могла бы разойтись с ней, например если
 *  человек открыл интерфейс в двух вкладках. */
function currentScheme() {
    return document.documentElement.dataset.pmkScheme === "light" ? "light" : "dark";
}

function applyScheme(scheme) {
    document.documentElement.dataset.pmkScheme = scheme;
    cookie.set(COOKIE, scheme);
}

export function colorSchemeItem() {
    const light = currentScheme() === "light";
    return {
        type: "switch",
        id: "pmk_color_scheme",
        // Подпись говорит про место, а не про цвет: «светлая тема» звучит как
        // вкусовщина, «для цеха» объясняет, когда её включать.
        description: _t("Светлый вид — для цеха"),
        isChecked: light,
        callback: () => applyScheme(light ? "dark" : "light"),
        // 45 — между разделителем (40) и «Мои настройки» (50): пункт про
        // рабочее место стоит выше пунктов про учётную запись.
        sequence: 45,
    };
}

registry.category("user_menuitems").add("pmk_color_scheme", colorSchemeItem);
