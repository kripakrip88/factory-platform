// Правый верхний угол: убираем то, чем завод не пользуется.
//
// Решение владельца 28.09.2026 (разбор UX, скрин 33): переключатель компаний,
// «Поддержка», «Мой аккаунт Odoo.com», «Shortcuts» и статус «в сети» из угла
// убрать. Они заняли место, из-за которого угол переехал на отдельную строку
// шапки, а пользы ноль.
//
// ⚠️ ПЕРЕКЛЮЧАТЕЛЬ КОМПАНИЙ убран совсем, а не «до второй компании». Компаний
// у завода будет несколько, но с общим складом и сотрудниками — это отдельная
// доработка, переключатель в углу её не решает (Антон, 28.09.2026). В Odoo 19
// он виден и при одной компании (просто неактивный), поэтому прятать условием
// «компаний больше одной» бессмысленно.
//
// Удаляем из реестров, а не прячем стилями: так пункты не рисуются вовсе и
// не ловят горячие клавиши (у переключателя — Shift+U).
//
// Порядок загрузки: модуль зависит от web и mail, поэтому этот файл
// выполняется ПОСЛЕ того, как они зарегистрировали свои пункты.
import { registry } from "@web/core/registry";

const systray = registry.category("systray");
if (systray.contains("SwitchCompanyMenu")) {
    systray.remove("SwitchCompanyMenu");
}

// support — «Поддержка» (ссылка на odoo.com); shortcuts — «Shortcuts»;
// odoo_account — «Мой аккаунт Odoo.com»; im_status — «Не в сети»/«В сети»
// из модуля mail; separator — черта, которая после этого отделяла бы пустоту.
// Остаются «Мои предпочтения», «Установить приложение» и «Выйти».
const userMenu = registry.category("user_menuitems");
for (const key of ["support", "shortcuts", "separator", "odoo_account", "im_status"]) {
    if (userMenu.contains(key)) {
        userMenu.remove(key);
    }
}
