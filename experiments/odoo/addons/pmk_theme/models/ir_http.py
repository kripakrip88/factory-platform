# -*- coding: utf-8 -*-
"""Выбранный вид темы — в разметку страницы, до первого кадра.

Почему вообще сервер, а не только JS. Если ставить атрибут скриптом, он
доедет после того, как браузер уже нарисовал страницу тёмными стилями: на
экране у станка полсекунды тёмного, потом рывок в светлое. Сервер отдаёт
атрибут прямо на <html>, и светлый вид приходит первым же кадром.

Почему кука, а не поле в карточке пользователя. Свет нужен НЕ человеку, а
МЕСТУ: у станка днём — светлый, в кабинете — тёмный. Один и тот же мастер
работает и там, и там под одной учётной записью. Поле в res.users заставило бы
его переключать вид при каждом переходе между цехом и кабинетом; кука живёт в
браузере конкретной машины и запоминает вид рабочего места.

Почему СВОЯ кука, а не штатная color_scheme. У Odoo 19 своя кука с таким
именем уже есть, и она переключает не цвета, а БАНДЛ: в webclient_bootstrap
при color_scheme == 'dark' вместо web.assets_web подключается
web.assets_web_dark. Тёмный вид стенда собран на обычном бандле, так что
воспользоваться штатной кукой значило бы подменить весь набор стилей — ровно
то, что запрещено требованием «тёмный вид обязан остаться прежним».
"""

from odoo import models
from odoo.http import request

COOKIE = "pmk_color_scheme"
SCHEMES = ("dark", "light")
# Умолчание — тёмный: так вид не меняется ни у кого, кто не нажимал
# переключатель. Новая возможность не имеет права менять чужой экран сама.
DEFAULT = "dark"


class IrHttp(models.AbstractModel):
    _inherit = "ir.http"

    def webclient_rendering_context(self):
        context = super().webclient_rendering_context()
        context["pmk_scheme"] = self._pmk_color_scheme()
        return context

    def _pmk_color_scheme(self):
        """Вид из куки. Всё, кроме двух известных значений, — тёмный.

        Проверка по списку, а не «что пришло, то и подставим»: значение куки
        уезжает прямо в атрибут разметки, и подставлять туда чужую строку
        нельзя.
        """
        value = request.httprequest.cookies.get(COOKIE)
        return value if value in SCHEMES else DEFAULT
