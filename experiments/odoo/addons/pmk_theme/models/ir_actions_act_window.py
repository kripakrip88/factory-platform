class IrActionsActWindow(models.Model):
    _inherit = "ir.actions.act_window"

    @api.model
    def _pmk_empty_help(self):
        """xml-id действия → наша подсказка пустого экрана."""
        return dict(EMPTY_HELP)

    def _get_action_dict(self):
        result = super()._get_action_dict()
        text = self._pmk_empty_help().get(result.get("xml_id"))
        if text:
            result["help"] = text
        return result
