# -*- coding: utf-8 -*-
"""Обратный счёт норматива резки из реальных замеров.

Порядок на участке перевёрнут намеренно: сначала копим замеры, потом получаем
норматив. Поэтому здесь не «паспортные режимы станка», а обратная задача — из
факта и знаменателя вывести, с какой скоростью мы на самом деле режем.

ЗНАМЕНАТЕЛЬ. «Лист резался 47 минут» непереносимо на другой заказ: неизвестно,
сколько в нём было метров реза, проколов и какая толщина. Поэтому замер без
длины реза и числа проколов в норматив не идёт вовсе — см. фильтрацию ниже.

МОДЕЛЬ ВРЕМЕНИ, слова владельца: время пробивов, нулевой пробег, время резки,
загрузка и разгрузка стола. Загрузка и разгрузка — константы станка, они
вычитаются до этого файла. Остаётся:

    минуты = длина_реза / скорость + проколы × время_прокола

Холостой пробег отдельным слагаемым НЕ выделен, и это осознанно: замерить его
нечем — оператор жмёт две кнопки, а не пять. Он сидит внутри обеих оценок,
поэтому «скорость» здесь — эффективная скорость участка, а не паспортная
скорость луча. Для планирования загрузки нужна как раз эффективная: планируем
мы стол, а не луч.

ПОЧЕМУ ОДНОГО ЗАМЕРА МАЛО. В уравнении два неизвестных. Один замер даёт одно
уравнение — разделить рез и проколы по нему невозможно. Больше того: если во
всех замерах на метр реза приходится одно и то же число проколов (а так и
бывает, когда режут одну и ту же деталь), уравнения линейно зависимы и
разделения нет даже при десяти замерах. В этих случаях функция честно
возвращает режим «рез и проколы не разделены» и одну переносимую величину —
минуты на метр реза. Выдумывать второе число она не станет.
"""

MODE_NONE = "none"           # ни одного пригодного замера
MODE_AGGREGATE = "aggregate"  # есть минуты на метр, но рез и проколы не разделены
MODE_FULL = "full"           # выведены и скорость, и время прокола

SECONDS_IN_MINUTE = 60.0
MM_IN_M = 1000.0

# Порог вырождения. Сравниваем определитель нормальной системы с произведением
# диагональных сумм: величина безразмерная, это по сути 1 − r² между длиной
# реза и числом проколов. Меньше порога — регрессоры идут «в ногу», и любое
# разделение будет не результатом замеров, а результатом шума в них.
DEGENERACY_LIMIT = 1e-4


def _usable(samples):
    """Отсеять замеры, по которым считать нечего.

    Нулевая длина реза — чертежи не разобраны, знаменателя нет. Нулевые или
    отрицательные минуты — замер не закрыт или закрыт раньше начала. Такие
    строки не «считаются как ноль», их просто нет в выборке, и их число
    возвращается отдельно, чтобы было видно, сколько замеров пропало впустую.
    """
    good, skipped = [], 0
    for length_m, pierces, minutes in samples:
        if (length_m or 0.0) > 0.0 and (minutes or 0.0) > 0.0:
            good.append((float(length_m), float(pierces or 0), float(minutes)))
        else:
            skipped += 1
    return good, skipped


def _spread_pct(good, predict):
    """Наибольшее расхождение факта с моделью, %. Это мера доверия: пока она
    держится в пределах десятка процентов, нормативу можно планировать смену;
    когда она за полсотни — в замерах сидит обед, поломка или чужой лист."""
    worst = 0.0
    for length_m, pierces, minutes in good:
        predicted = predict(length_m, pierces)
        worst = max(worst, abs(predicted - minutes) / minutes * 100.0)
    return worst


def fit_norm(samples):
    """Вывести норматив из замеров.

    samples — последовательность (длина реза в метрах, число проколов, минуты).
    Минуты — ЧИСТОЕ время резки: загрузка и разгрузка стола уже вычтены.

    Возвращает словарь с ключами mode, sample_count, skipped, min_per_m,
    speed_mm_min, pierce_time_s, spread_pct, reason. Значения, которые вывести
    не удалось, остаются нулями — и режим говорит, почему. Пустое честнее
    выдуманного: расчёт по толщине без замеров обязан показывать «норматива
    нет», а не среднее по соседним толщинам.
    """
    empty = {
        "mode": MODE_NONE, "sample_count": 0, "skipped": 0,
        "min_per_m": 0.0, "speed_mm_min": 0.0, "pierce_time_s": 0.0,
        "spread_pct": 0.0, "reason": "нет ни одного пригодного замера",
    }
    good, skipped = _usable(samples)
    if not good:
        empty["skipped"] = skipped
        return empty

    total_minutes = sum(row[2] for row in good)
    total_length = sum(row[0] for row in good)
    min_per_m = total_minutes / total_length

    result = {
        "mode": MODE_AGGREGATE, "sample_count": len(good), "skipped": skipped,
        "min_per_m": min_per_m, "speed_mm_min": 0.0, "pierce_time_s": 0.0,
        "spread_pct": _spread_pct(good, lambda length, _p: length * min_per_m),
        "reason": "",
    }

    if len(good) < 2:
        result["reason"] = ("один замер: в уравнении два неизвестных, "
                            "рез и проколы по нему не разделить")
        return result

    # Нормальные уравнения метода наименьших квадратов для модели
    # минуты = alpha × длина + beta × проколы (без свободного члена: лист без
    # реза не занимает станок вовсе, и свободный член тут означал бы время,
    # которое берётся ниоткуда).
    s_ll = sum(row[0] * row[0] for row in good)
    s_pp = sum(row[1] * row[1] for row in good)
    s_lp = sum(row[0] * row[1] for row in good)
    s_ly = sum(row[0] * row[2] for row in good)
    s_py = sum(row[1] * row[2] for row in good)

    if s_pp <= 0.0:
        result["reason"] = "ни в одном замере не указаны проколы"
        return result

    determinant = s_ll * s_pp - s_lp * s_lp
    if determinant <= DEGENERACY_LIMIT * s_ll * s_pp:
        result["reason"] = ("во всех замерах на метр реза приходится одно и то же "
                            "число проколов — нужен замер с другим соотношением")
        return result

    alpha = (s_pp * s_ly - s_lp * s_py) / determinant   # минут на метр реза
    beta = (s_ll * s_py - s_lp * s_ly) / determinant    # минут на прокол

    if alpha <= 0.0 or beta < 0.0:
        # Отрицательное время прокола физического смысла не имеет: значит
        # замеры противоречат друг другу (разная смена, разный металл, обед
        # внутри замера). Отдаём переносимое среднее и называем причину.
        result["reason"] = ("обратный счёт дал отрицательную величину — замеры "
                            "противоречивы, разделять их нельзя")
        return result

    result.update({
        "mode": MODE_FULL,
        "speed_mm_min": MM_IN_M / alpha,
        "pierce_time_s": beta * SECONDS_IN_MINUTE,
        "spread_pct": _spread_pct(good, lambda length, pierces: alpha * length + beta * pierces),
    })
    return result


def estimate_minutes(mode, min_per_m, speed_mm_min, pierce_time_s, cut_length_m, pierces):
    """Сколько минут займёт резка по нормативу. None — значит норматива нет.

    None здесь возвращается специально, а не ноль: ноль минут сложился бы в
    сумме загрузки участка с настоящими минутами и тихо занизил бы план.
    Пусто должно оставаться пустым до самого экрана.
    """
    if not cut_length_m or cut_length_m <= 0.0:
        return None
    if mode == MODE_FULL and speed_mm_min > 0.0:
        return cut_length_m * MM_IN_M / speed_mm_min + (pierces or 0) * pierce_time_s / SECONDS_IN_MINUTE
    if mode == MODE_AGGREGATE and min_per_m > 0.0:
        # Проколы здесь уже сидят в минутах на метр — прибавлять их отдельно
        # значит посчитать их дважды.
        return cut_length_m * min_per_m
    return None
