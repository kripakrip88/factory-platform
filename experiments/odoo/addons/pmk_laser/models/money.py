# -*- coding: utf-8 -*-
"""Деньги и баланс металла на участке лазерной резки.

Здесь только чистая арифметика: числа на входе, числа на выходе. Ни ORM, ни
запросов — поэтому её можно прогнать по живым файлам завода, не поднимая Odoo,
и именно так она проверена. Контрольные цифры на трёх раскроях за 08.09.2026:

    Отводы 10 мм, 4 листа 1500x6000, использование 66,7/65,0/51,7/25,6%
        -> 1476,4 кг полезного веса -> 738,20 ₽ премии
    Кронштейны 2 мм, 8 листов 1000x4000, 89,2% семь раз и 40,2%
        -> 417,5 кг -> 1252,44 ₽
    Площадка ГРПШ 3 мм, 1 лист 1500x3000, 73,0%
        -> 77,3 кг -> 38,67 ₽

Два правила владельца, ради которых модуль вообще существует.

ПОЛЕЗНЫЙ ВЕС — вес разложенных деталей, а не купленного листа. За детали
платит заказчик, от них же считается премия. Считать премию от веса листа
нельзя: тогда за плохую раскладку платят больше, чем за хорошую.

МАССА БЕРЁТСЯ ИЗ СПРАВОЧНИКА (кг/м² листа), а НЕ через плотность. Это не
вкусовщина: у рифлёного листа квадратный метр на 5–7% тяжелее гладкого той же
толщины, у просечно-вытяжного металла остаётся 37–63% габарита. Формула
«площадь × толщина × 7850» на них соврала бы, а справочник pmk_calc — знает.
Поэтому во всех функциях ниже входной параметр называется mass_per_sqm, и
плотности в этом файле нет ни одной.

Ставка премии сюда НЕ переписана, а взята из tools/lxds.py: разбор файла и
расчёт по нему обязаны жить на одной ставке. Две копии числа 500 рано или
поздно разъедутся, и разъедутся молча — в деньгах.
"""

from ..tools.lxds import (  # noqa: F401  (константы реэкспортируются наружу)
    PREMIUM_BOUNDARY_MM,
    PREMIUM_RATE_THICK,
    PREMIUM_RATE_THIN,
    premium_rate,
)

KG_IN_TON = 1000.0
MM2_IN_M2 = 1_000_000.0

# Ширина реза. CypCut пишет её в Technical/content.xml как CutGap="0,2", но
# этот раздел у технолога демонстрационный и во всех трёх файлах побайтово
# одинаков — поэтому значение здесь своё, а из файла берётся только справочно.
DEFAULT_KERF_MM = 0.2

# Шаг округления предлагаемого обрезка. Кладовщик меряет рулеткой, и обрезок
# «4466,9 мм» он всё равно запишет как 4400: лишняя точность тут не точность,
# а видимость точности. Округляем ВНИЗ — чтобы предложенный кусок гарантированно
# существовал в металле, а не оказался на сантиметр длиннее реального.
OFFCUT_STEP_MM = 100.0

# Короче этого остаток в реестр не заводят: место на стеллаже дороже металла.
DEFAULT_MIN_OFFCUT_MM = 300.0


def sheet_area_m2(width_mm, length_mm):
    """Габаритная площадь одного листа, м²."""
    return (width_mm or 0.0) * (length_mm or 0.0) / MM2_IN_M2


def useful_area_m2(area_m2, utilization_pct):
    """Полезная площадь: та доля габарита, что превратилась в детали.

    Использование CypCut считает сам и пишет в Utilization каждой раскладки.
    Своего раскроя мы не делаем, поэтому это единственный источник — и он
    честный: программа знает точные контуры, мы их пока нет.
    """
    return (area_m2 or 0.0) * (utilization_pct or 0.0) / 100.0


def mass_kg(area_m2, mass_per_sqm):
    """Масса площади по справочнику. Ровно одно умножение — и ровно поэтому
    справочник обязан быть заполнен: пустая масса даст ноль, а не «примерно»."""
    return (area_m2 or 0.0) * (mass_per_sqm or 0.0)


def premium_rub(useful_mass_kg, thickness_mm):
    """Премия за задание, ₽. Ставка зависит от толщины: тонкий лист на тонну
    трудоёмче, там деталей в разы больше при том же весе.

    Проверка на живых файлах: 1476,4 кг десятки -> 738,20 ₽; 417,5 кг двойки ->
    1252,44 ₽. На кронштейнах полезного веса втрое меньше, а премия вдвое
    больше — ставка работает так, как задумал владелец.
    """
    return (useful_mass_kg or 0.0) / KG_IN_TON * premium_rate(thickness_mm or 0.0)


def split_rub(total_rub, count):
    """Разделить премию поровну между операторами. Возвращает список долей.

    Делим В КОПЕЙКАХ, а не в рублях. Причина простая: 738,20 на троих в рублях
    даёт 246,0666…, и после округления каждой доли сумма долей не сойдётся с
    премией. Здесь неделимый остаток раздаётся по копейке первым в списке, и
    сумма долей РАВНА премии всегда — иначе расхождение вылезет в ведомости.

    Состав смены живёт в задании списком: один оператор получает всё, трое —
    на троих. Менять код при смене состава не нужно, это требование владельца.
    """
    if not count or count < 1:
        return []
    kopecks = int(round((total_rub or 0.0) * 100.0))
    base, rest = divmod(kopecks, count)
    return [(base + (1 if index < rest else 0)) / 100.0 for index in range(count)]


def kerf_area_m2(cut_length_m, kerf_mm=DEFAULT_KERF_MM):
    """Площадь, которую рез уносит в пыль.

    На каждом метре реза исчезает полоска шириной kerf_mm на всю толщину листа.
    Считаем её именно площадью, а не объёмом: массу потом даст тот же кг/м²
    справочника, и плотность снова не нужна. На десятке метр реза = 0,0002 м² =
    15,7 г — без этой строки лом в балансе всегда «больше расчётного», и никто
    не понимает почему.
    """
    return (cut_length_m or 0.0) * 1000.0 * (kerf_mm or 0.0) / MM2_IN_M2


def scrap_mass_kg(sheets_kg, useful_kg, offcut_kg, kerf_kg):
    """Лом = что списали минус детали, обрезки и пропил.

    Баланс владельца: вес списанных листов = детали + обрезки + лом. Лом здесь
    не вводят, а получают вычитанием — и в этом весь смысл: систематический
    перекос в лом означает либо что обрезки не оприходуют, либо что раскладка
    плохая. Сейчас этого не видит никто.

    Результат может выйти отрицательным — значит обрезков оприходовано больше,
    чем физически было металла. Это не ошибка формулы, а сигнал, и модель
    показывает его как есть.
    """
    return (sheets_kg or 0.0) - (useful_kg or 0.0) - (offcut_kg or 0.0) - (kerf_kg or 0.0)


def propose_offcut(width_mm, length_mm, utilization_pct,
                   step_mm=OFFCUT_STEP_MM, min_length_mm=DEFAULT_MIN_OFFCUT_MM):
    """Предложить размер обрезка. Возвращает (ширина, длина) или None.

    Предложение ГРУБОЕ, и это надо говорить вслух. Точный свободный
    прямоугольник считается по геометрии раскладки, а она лежит в двоичной
    части файла (Shapes2D/data.bin). Пока считаем так: детали кладут с одного
    края, значит свободной остаётся полоса во всю ширину листа длиной
    «габарит × (1 − использование)».

    На четвёртом листе отводов (1500x6000, занято 25,6%) получается полоса
    1500 x 4400 — тот самый кусок, который сейчас уезжает в лом, хотя это
    цельная заготовка. Когда разберём геометрию, предложение станет точным,
    а порядок работы оператора не изменится: система предлагает — технолог
    смотрит на лист своими глазами и правит.
    """
    free_mm = (length_mm or 0.0) * (1.0 - (utilization_pct or 0.0) / 100.0)
    if step_mm and step_mm > 0:
        free_mm = int(free_mm / step_mm) * step_mm
    if free_mm < (min_length_mm or 0.0):
        return None
    return (width_mm, float(free_mm))
