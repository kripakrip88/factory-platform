# -*- coding: utf-8 -*-
"""Производственный заказ: клиент и состояние одним словом.

ДВЕ ВЕЩИ, КОТОРЫХ У ЗАКАЗА НЕТ, А ЦЕХУ НУЖНЫ.

1. КЛИЕНТ. mrp.production не имеет partner_id — проверено запросом к
   ir_model_fields на живом стенде, а не по памяти. Это не недосмотр Odoo:
   производственный заказ может быть заведён под склад, и тогда клиента у него
   нет вовсе. Путь до клиента такой: заказ → строка заказа на продажу
   (sale_line_id) → заказ на продажу → партнёр. Если заказ завели руками,
   остаётся текстовое поле «Источник» (origin) — им и подписываемся.

2. СОСТОЯНИЕ ДЛЯ ЦЕХА. Штатное state отвечает на вопрос «что с документом»
   (черновик / подтверждён / в процессе / готов). Начальника цеха занимает
   другой вопрос — «горит или нет», а это НЕ состояние документа: просрочка
   складывается из состояния, срока и сегодняшней даты. Поэтому здесь своё
   поле из четырёх слов прототипа.
"""

from odoo import api, fields, models


class MrpProduction(models.Model):
    _inherit = "mrp.production"

    # ─── Клиент ───────────────────────────────────────────────────────────
    #
    # Char, а не Many2one, и НЕ хранимое — осознанно, у обоих решений есть цена.
    #
    # Many2one дал бы сортировку и группировку, но показывал бы пусто у всех
    # заказов, заведённых без продажи, — а таких на заводе большинство, пока
    # цепочка «КП → заказ → производство» не собрана целиком. Колонка, пустая
    # у большинства строк, хуже отсутствующей: её перестают читать.
    #
    # Хранимое поле дало бы сортировку, но потребовало бы жёсткой зависимости
    # от sale_mrp в @api.depends (иначе Odoo не соберёт реестр). Плата за
    # нехранимое — колонка не сортируется и не ищется. Сортировать список
    # цеха всё равно осмысленно по сроку, а не по клиенту.
    #
    # ПОДПИСЬ КОЛОНКИ — «Клиент / источник», а не «Клиент», и это не
    # многословие. В запасном варианте сюда попадает origin, а origin клиентом
    # не является: у заказа, порождённого правилом пополнения, там ссылка на
    # документ-источник, у заведённого руками — то, что написал технолог.
    # Колонка «Клиент» со строкой вида «ПЗ/00014» внутри — это не «почти
    # клиент», это неверные данные под верной подписью. Выбор был между пустой
    # колонкой у большинства строк и честной подписью; выбрана подпись.
    pmk_customer_display = fields.Char(
        "Клиент / источник",
        compute="_compute_pmk_customer_display",
        help="Клиент из связанного заказа на продажу. Если продажи за заказом "
             "нет — показывается штатное поле «Источник» (origin): это может "
             "быть и ссылка на документ, а не имя клиента.",
    )

    # ─── Состояние для цеха ───────────────────────────────────────────────
    #
    # Нехранимое ОБЯЗАТЕЛЬНО, и это не экономия на индексе: «просрочен»
    # зависит от текущего времени. Хранимая колонка не пересчитывается сама
    # от того, что наступило утро, — заказ, вчера бывший «в работе», сегодня
    # так и остался бы «в работе» в базе. Поле, которое врёт к следующему
    # утру, хуже, чем поле без сортировки.
    pmk_status = fields.Selection(
        [
            ("late", "Просрочен"),
            ("progress", "В работе"),
            ("todo", "Не начато"),
            ("done", "Готово"),
            ("cancel", "Отменён"),
        ],
        string="Состояние",
        compute="_compute_pmk_status",
        help="Состояние заказа глазами цеха: срок уже прошёл, работа идёт, "
             "ещё не начинали или сдано.",
    )

    # ─── Плановые часы операций ───────────────────────────────────────────
    #
    # Поле-переводчик единиц, и заведено оно ради одной конкретной ошибки.
    #
    # Штатное mrp.production.duration_expected — это МИНУТЫ: в ядре
    # (mrp/models/mrp_production.py:157) у него help «Total expected duration
    # (in minutes)», а собирается оно суммой mrp.workorder.duration_expected,
    # где в mrp/models/mrp_workorder.py:88-90 прямо стоит «# in minutes».
    # Виджет float_time читает то же число как ЧАСЫ (web/static/src/views/
    # fields/formatters.js, formatFloatTime: hour = Math.floor(value)).
    # Отдать ему минуты — соврать ровно в 60 раз: план на 90 минут рисуется
    # «90:00» и читается как девяносто часов.
    #
    # Поймать это глазами на стенде НЕЛЬЗЯ: рабочих заданий ноль, сумма всегда
    # 0, и плашка честно показывает «00:00» при любой ошибке в единицах.
    # Поэтому перевод живёт в модели, а не в голове у того, кто смотрит форму,
    # и в вид уходит ЭТО поле, а не duration_expected. В штатном списке mrp то
    # же duration_expected выведено через float_time (проверено на собранном
    # arch стенда) — этот приём не образец, повторять его не надо.
    #
    # Нехранимое: duration_expected в ядре и само нехранимое (compute без
    # store), хранить производное от нехранимого нечем.
    pmk_duration_hours = fields.Float(
        "План по операциям, ч",
        compute="_compute_pmk_duration_hours",
        digits=(10, 2),
        help="Плановая длительность рабочих заданий заказа в ЧАСАХ. Штатное "
             "поле «Плановая трудоемкость» (duration_expected) хранит минуты.",
    )

    @api.depends("duration_expected")
    def _compute_pmk_duration_hours(self):
        for production in self:
            production.pmk_duration_hours = (production.duration_expected or 0.0) / 60.0

    # Зависимость объявлена только от origin, хотя читаем мы ещё и
    # sale_line_id. Написать в @api.depends путь 'sale_line_id.order_id.
    # partner_id' нельзя: поле sale_line_id приносит модуль sale_mrp, и на
    # установке без него Odoo не соберёт реестр — упадёт весь стенд, а не одна
    # колонка. Потеря от неполного depends здесь нулевая: поле нехранимое,
    # кэш живёт внутри одного запроса, и следующее открытие списка всё равно
    # считает заново.
    @api.depends("origin")
    def _compute_pmk_customer_display(self):
        # Проверяем наличие поля, а не установленность модуля: так код честно
        # отвечает на вопрос «могу ли я это прочитать», не гадая, какой модуль
        # его когда-нибудь принесёт.
        has_sale_link = "sale_line_id" in self._fields
        for production in self:
            partner = False
            if has_sale_link and production.sale_line_id:
                partner = production.sale_line_id.order_id.partner_id
            # display_name, а не name: у контрагента-подразделения name — это
            # «Отдел снабжения», и без родителя строка бессмысленна.
            production.pmk_customer_display = (
                partner.display_name if partner else (production.origin or "")
            )

    # is_delayed — штатное поле mrp.production (нехранимое, считается от
    # datetime.now()). Не пересчитываем просрочку сами: правило «срок прошёл
    # ИЛИ плановое окончание позже срока» уже описано в ядре
    # (_compute_is_delayed), и второй его экземпляр рано или поздно разойдётся
    # с первым — тогда список и форма начнут спорить друг с другом.
    @api.depends("state", "is_delayed")
    def _compute_pmk_status(self):
        for production in self:
            if production.state == "cancel":
                production.pmk_status = "cancel"
            elif production.state == "done":
                production.pmk_status = "done"
            elif production.is_delayed:
                # Просрочка важнее «в работе»: заказ может идти и гореть
                # одновременно, но на экране нужно ОДНО слово, и это оно.
                production.pmk_status = "late"
            elif production.state in ("progress", "to_close"):
                # to_close — «осталось закрыть»: работа уже сделана, но
                # документ не проведён. Для цеха это всё ещё «в работе».
                production.pmk_status = "progress"
            else:
                # draft и confirmed: подтверждённый заказ, к которому ещё не
                # приступали, для цеха ничем не отличается от черновика.
                production.pmk_status = "todo"
