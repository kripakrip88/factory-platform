# -*- coding: utf-8 -*-
"""ТПР 901-09-11.84, альбом II — проставки монтажные Ду 100–600 (черт. 1219.01.000).

Источник — присланный Антоном скан (meganorm 4293845918), PDF-страница 25: «эскизный
чертёж общего вида» по материалам Союзводоканалпроекта (черт. М621.00.80) + таблица
размеров dy, dн, Д, Д1, Д2, Д3, e, e1, e2, e3, S, S1, B, L, ход, масса.
Документация — docs/TPR_901-09-11.84.md.

⚠ ЭСКИЗ, не рабочий чертёж: в альбоме нет числа и диаметра отверстий фланцев, толщины
присоединительных фланцев, шпилек, уплотнения. Состав собран так (проверить Игорю):
- Д и Д1 точно совпадают с присоединительными размерами фланцев ГОСТ 12815-80 на Ру 1,0 МПа —
  оттуда число и диаметр отверстий, размер шпилек (второй источник);
- 4 фланца — кольца Д × (dн + 2) толщиной B: два присоединительных, сальниковый (приварен к
  наружному патрубку) и нажимной;
- наружный патрубок dн×S длиной e2, внутренний — L − e2 + e;
- n шпилек через сальниковые и правые фланцы, по 4 гайки на шпильку (так на эскизе);
- уплотнение — покупное.
Масса такого состава — 94–114 % от массы альбома (сверка в справочнике).
"""
import math

from .common import part, pipe_kg_m, ring_kg

ALBUM = "ТПР 901-09-11.84"
ALBUM_FULL = "ТПР 901-09-11.84, альбом II"

TYPES = {
    "pr": dict(code="Проставка", label="Проставка монтажная Ду 100–600 (эскиз)", album=ALBUM_FULL),
}

# dy → (обозначение, dн, Д, Д1, Д2, Д3, e, e1, e2, e3, S, S1, B, L, ход, масса альбома).
PR = {
    100: ("1219.01.000", 108, 215, 180, 99, 97, 30, 50, 95, 115, 5.5, 3.5, 20, 220, 10, 24),
    150: ("1219.01.000-01", 159, 280, 240, 149, 147, 35, 55, 125, 140, 6, 4, 20, 275, 15, 33),
    300: ("1219.01.000-02", 325, 440, 400, 311, 309, 55, 80, 150, 165, 8, 6, 25, 325, 30, 78),
    400: ("1219.01.000-03", 426, 565, 515, 412, 410, 65, 95, 225, 170, 8, 6, 26, 405, 40, 138),
    500: ("1219.01.000-04", 530, 670, 620, 516, 514, 65, 98, 235, 175, 8, 4, 28, 420, 40, 191),
    600: ("1219.01.000-05", 630, 780, 725, 612, 610, 65, 100, 250, 185, 8, 4, 31, 450, 40, 259),
}
FIELDS = ("des", "dn", "D", "D1", "D2", "D3", "e", "e1", "e2", "e3", "S", "S1", "B", "L", "hod", "mass")
# ГОСТ 12815-80, Ру 1,0 МПа: dy → (число отверстий, ⌀ отверстия, шпилька М).
FLANGE = {100: (8, 18, 16), 150: (8, 22, 20), 300: (12, 22, 20), 400: (16, 26, 24),
          500: (20, 26, 24), 600: (20, 30, 27)}
NUT_KG = {16: 0.034, 20: 0.063, 24: 0.109, 27: 0.165}  # ГОСТ 5915-70


def _mark(dy):
    return "Ду%s" % dy


def marks(kind):
    return [_mark(dy) for dy in PR]


def row(mark):
    return dict(zip(FIELDS, PR[int(mark[2:])]))


def check(kind, mark):
    if mark not in marks(kind):
        return "Проставки %s в альбоме нет — бывают Ду 100, 150, 300, 400, 500, 600" % mark
    return ""


def stud_length(mark):
    r = row(mark)
    m = FLANGE[int(mark[2:])][2]
    return int(math.ceil((r["L"] - r["e2"] + r["B"] + 2.6 * m) / 10.0) * 10)


def outside_album(kind, mark):
    return ""


def dims(kind, mark):
    r = row(mark)
    return dict(length=r["L"], width=r["D"], dn=r["dn"], thickness=r["B"])


def parts(kind, mark, bend_k=None):
    dy = int(mark[2:])
    r = row(mark)
    n, d_hole, m = FLANGE[dy]
    ring = ring_kg(r["D"], r["dn"] + 2, r["B"], n, d_hole)
    pipe = pipe_kg_m(r["dn"], r["S"])
    pipe_mat = [("profile", "Труба круглая", "%sx%s" % (r["dn"], ("%g" % r["S"])))]
    flange = "⌀%s/%s, %s отв. ⌀%s на ⌀%s — лист %s" % (r["D"], r["dn"] + 2, n, d_hole, r["D1"], r["B"])
    sl = stud_length(mark)
    return [
        part("flange", 1, "Фланец присоединительный %s" % flange, 2, ring, [("sheet", r["B"])]),
        part("gland", 2, "Фланцы сальниковый и нажимной %s" % flange, 2, ring, [("sheet", r["B"])]),
        part("pipe_out", 3, "Патрубок наружный — труба %s×%s L=%s" % (r["dn"], "%g" % r["S"], r["e2"]), 1,
             pipe * r["e2"] / 1000.0, pipe_mat),
        part("pipe_in", 4, "Патрубок внутренний — труба %s×%s L=%s" % (r["dn"], "%g" % r["S"], r["L"] - r["e2"] + r["e"]), 1,
             pipe * (r["L"] - r["e2"] + r["e"]) / 1000.0, pipe_mat),
        part("stud", 5, "Шпилька М%s×%s" % (m, sl), n, math.pi / 4 * m * m * 7.85e-6 * sl),
        part("nut", 6, "Гайка М%s ГОСТ 5915-70" % m, 4 * n, NUT_KG[m]),
        part("seal", 7, "Уплотнение сальника — резиновое кольцо Ду %s" % dy, 1, 0.0),
    ]


def album_mass(kind, mark):
    return row(mark)["mass"]


def designation(kind, mark):
    return "%s (%s)" % (row(mark)["des"], mark)


def name(kind, mark, steel):
    return "Проставка монтажная %s (%s) %s" % (mark.replace("Ду", "Ду "), row(mark)["des"], ALBUM)


def short(kind, mark, steel):
    r = row(mark)
    return "Проставка %s · L %s · ход %s · эскиз" % (mark.replace("Ду", "Ду "), r["L"], r["hod"])


def history_patterns(kind, mark):
    return [r"проставк", r"д[уy]\s*%s(\D|$)" % mark[2:]], None
