# -*- coding: utf-8 -*-
"""Два показателя шапки КП, которых в Odoo нет: вес заказа и число позиций.

ПОЧЕМУ ВЕС СЧИТАЕТСЯ ЗДЕСЬ, А НЕ БЕРЁТСЯ ИЗ СПЕЦИФИКАЦИИ. У нас есть
pmk.metal.spec — калькулятор, который считает вес изделия по деталям и знает
его точно. Связи «спецификация ↔ заказ на продажу» в базе не существует
(проверено на стенде), и заводить её ради одного числа в шапке дороже, чем
сложить вес по позициям заказа: связь придётся поддерживать в обе стороны,
решать, что делать при нескольких спецификациях на заказ, и переносить её
через все будущие миграции. Когда мост pmk_bridge доведёт номенклатуру до
спецификаций, вес можно будет брать оттуда — тогда это станет уточнением
одной формулы, а не новой сущностью.

ЧТО ЗНАЧИТ `weight` В ODOO. Это вес ОДНОЙ единицы измерения номенклатуры, а не
штуки. На стенде 752 карточки: 665 в метрах (weight = кг/м, от 0,154 до 314 —
это погонный вес профиля), 81 в штуках (weight = кг/шт), 6 в килограммах
(weight = 1, то есть килограмм весит килограмм). Поэтому произведение
«количество × weight» даёт килограммы во всех трёх случаях — но только пока
единица строки совпадает с единицей карточки. Если менеджер поставил в строке
другую единицу (заказ в тоннах при карточке в метрах), количество приводится
к единице карточки, иначе вес выйдет в тысячи раз больше.

ОГРАНИЧЕНИЕ, КОТОРОЕ НАДО ЗНАТЬ. Odoo 19 больше не держит единицы по
категориям: `_compute_quantity` просто делит коэффициенты и при
несопоставимых единицах (метры → штуки) молча возвращает число, в котором
нет смысла. Поэтому перед пересчётом спрашиваем `_has_common_reference`, и
если общего эталона нет — позиция в вес НЕ входит. Лучше недосчитанный
килограмм, чем нарисованная тонна: по весу заказывают машину.
"""

from odoo import api, fields, models

# Килограммы в тонну. Вынесено в имя, чтобы в формуле не стояло голое 1000.0.
KG_IN_TON = 1000.0


class SaleOrder(models.Model):
    _inherit = "sale.order"

    # Оба поля НЕ хранимые, и это осознанно.
    #
    # Хранение нужно ради трёх вещей: сортировки в списке, фильтра в поиске и
    # группировки в отчёте. Ни одна из них сейчас не заказана — показатели
    # живут в шапке открытого документа. Зато у хранения есть цена, которую
    # платят сразу: колонка в таблице, пересчёт при каждой правке строки и —
    # главное — полный пересчёт по всем заказам при установке и при каждом
    # `-u pmk_sale`. На пустом стенде это ничто, на боевой базе с историей
    # заказов это минуты простоя на ровном месте.
    #
    # Плата за отказ: по весу нельзя отсортировать список КП и нельзя построить
    # сводку. Как только это понадобится — добавить store=True и миграцию,
    # правка на одну строку, зато сейчас её никто не оплачивает.
    pmk_weight_t = fields.Float(
        string="Вес, т",
        compute="_compute_pmk_head_totals",
        # Три знака = килограммы. Металл считают до килограмма, округление до
        # десятых тонны теряет 50 кг — это уже деньги.
        digits=(12, 3),
        help="Сумма по позициям: количество × вес единицы номенклатуры. "
             "Позиции, единицу которых нельзя привести к единице карточки, "
             "в сумму не входят.",
    )
    pmk_line_count = fields.Integer(
        string="Позиций",
        compute="_compute_pmk_head_totals",
        help="Только товарные строки. Разделы и заметки внутри таблицы "
             "позиций не считаются.",
    )

    # В зависимостях перечислены ПОЛЯ строк, а не сама таблица: от `order_line`
    # целиком пересчёт срабатывает на добавление и удаление строки, но не на
    # правку количества в уже существующей — а именно её правят чаще всего.
    @api.depends(
        "order_line.display_type",
        "order_line.product_id",
        "order_line.product_uom_id",
        "order_line.product_uom_qty",
    )
    def _compute_pmk_head_totals(self):
        for order in self:
            weight_kg = 0.0
            positions = 0

            for line in order.order_line:
                # display_type заполнен у разделов и заметок — это оформление
                # таблицы, а не позиции заказа. У них нет ни номенклатуры, ни
                # количества, и считать их «строками» — вводить в заблуждение.
                if line.display_type:
                    continue

                positions += 1

                product = line.product_id
                # Вес у нас заполнен везде, но модуль обязан пережить карточку
                # без веса: она появится в первый же день, когда заведут услугу
                # (монтаж, доставка) — у услуги веса нет и быть не должно.
                if not product or not product.weight:
                    continue

                qty = line.product_uom_qty
                line_uom = line.product_uom_id
                product_uom = product.uom_id

                if line_uom and product_uom and line_uom != product_uom:
                    # См. шапку файла: без общего эталона Odoo 19 вернёт число
                    # без смысла и не предупредит. Такую позицию пропускаем.
                    if not line_uom._has_common_reference(product_uom):
                        continue
                    # round=False обязателен. По умолчанию метод округляет ВВЕРХ
                    # до точности целевой единицы — на десятке строк это
                    # приписало бы заказу лишние килограммы из воздуха.
                    qty = line_uom._compute_quantity(
                        qty, product_uom, round=False,
                    )

                weight_kg += qty * product.weight

            order.pmk_weight_t = weight_kg / KG_IN_TON
            order.pmk_line_count = positions
