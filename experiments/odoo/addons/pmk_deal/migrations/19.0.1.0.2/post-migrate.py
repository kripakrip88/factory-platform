"""Стадии воронки — шаги завода: «Заявка → Расчёт → КП отправлено → Выиграно».

Разбор UX, шаг 4 (решение Антона 28.09.2026). Штатные «Новый →
Квалифицированный → Предложение» — язык продажников: непонятно, что нужно
сделать, чтобы перейти дальше; «Новый» ещё и не согласуется со словом
«сделка». «Выиграно» остаётся как есть. Пятую стадию «Согласование» не
заводим: согласование — наблюдение Антона, а не шаг (решение 23.09).

ПОЧЕМУ МИГРАЦИЯ, А НЕ DATA-ФАЙЛ. Стадии принадлежат модулю crm и записаны с
noupdate: data-файл с noupdate на обновлении их пропустит, а без noupdate —
будет затирать названия на каждом деплое, в том числе те, что Антон потом
поменяет сам в настройках CRM. Миграция отрабатывает один раз.

ПЕРЕИМЕНОВЫВАЕМ, ТОЛЬКО ЕСЛИ НАЗВАНИЕ ЕЩЁ ШТАТНОЕ. Если стадию уже
переименовали руками — не трогаем. Сделки остаются на своих стадиях: меняется
только подпись. Старые записи в ленте («Новый → Предложение») остаются со
старыми названиями — это история, Odoo хранит её текстом.

Название — переводимое поле (jsonb по языкам). Включены два языка, ru_RU и
en_US, пишем оба ключа: иначе при чтении на en_US осталось бы «New».

«Требования» — подсказка при наведении на заголовок колонки воронки. Это
пояснение, что значит стадия, а не запрет перехода. Пишем, только если пусто.
"""

STAGES = [
    # xmlid в crm, штатные названия (ru, en), новые (ru, en), подсказка
    ("stage_lead1", ("Новый", "New"), ("Заявка", "Request"),
     "Письмо разобрано, сделка заведена. Дальше — расчёт."),
    ("stage_lead2", ("Квалифицированный", "Qualified"), ("Расчёт", "Costing"),
     "Создан расчёт: считаем металл и работу."),
    ("stage_lead3", ("Предложение", "Proposition"), ("КП отправлено", "Quote sent"),
     "КП ушло клиенту, ждём решения."),
    ("stage_lead4", ("Выиграно", "Won"), ("Выиграно", "Won"),
     "Клиент согласился — дальше заказ."),
]


def migrate(cr, version):
    for xmlid, (old_ru, old_en), (new_ru, new_en), hint in STAGES:
        cr.execute(
            """
            UPDATE crm_stage s
               SET name = s.name || jsonb_build_object('ru_RU', %s, 'en_US', %s)
              FROM ir_model_data d
             WHERE d.module = 'crm' AND d.name = %s
               AND d.model = 'crm.stage' AND d.res_id = s.id
               AND COALESCE(s.name->>'ru_RU', s.name->>'en_US') IN (%s, %s)
            """,
            (new_ru, new_en, xmlid, old_ru, old_en),
        )
        cr.execute(
            """
            UPDATE crm_stage s
               SET requirements = %s
              FROM ir_model_data d
             WHERE d.module = 'crm' AND d.name = %s
               AND d.model = 'crm.stage' AND d.res_id = s.id
               AND COALESCE(s.requirements, '') = ''
            """,
            (hint, xmlid),
        )
