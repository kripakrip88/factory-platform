/**
 * Какие варианты переключателя показывать — разбор UX, шаг 29 (02.10.2026).
 * Чистая функция без импортов Odoo: её прогоняет node вне браузера.
 * Использует js/radio_hide_field.js (виджет pmk_radio_hide).
 *
 * ПРАВИЛО. Варианты из списка скрытых не показываются — кроме ТЕКУЩЕГО
 * значения записи: у старого адреса с «Прочее» переключатель покажет
 * «Прочее» отмеченным, иначе запись выглядела бы так, будто тип не выбран, а
 * сохранение молча оставило бы прежнее значение. Выбрал другой вариант —
 * скрытый пропадает. Данные не меняются, отбор — только на экране.
 *
 * @param {Array<[any, string]>} items варианты поля ([значение, подпись])
 * @param {Array} [hidden] значения, которые не показывать
 * @param {any} [current] текущее значение записи
 * @returns {Array<[any, string]>}
 */
export function visibleItems(items, hidden, current) {
    const skip = new Set(hidden || []);
    return (items || []).filter(([value]) => !skip.has(value) || value === current);
}
