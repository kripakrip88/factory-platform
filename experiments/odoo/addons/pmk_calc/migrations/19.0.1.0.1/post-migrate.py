# -*- coding: utf-8 -*-
"""Принудительный пересчёт эскизов у ВСЕХ позиций доборки.

Зачем скрипт вообще нужен. Поле pmk.dobor.order.line.sketch — вычисляемое и
ХРАНИМОЕ. Odoo пересчитывает такое поле при обновлении модуля только тогда,
когда само создаёт под него колонку; колонка pmk_dobor_order_line.sketch уже
есть с прошлой установки, поэтому обновление модуля старые эскизы не тронет —
в базе останется SVG, нарисованный прежним генератором.

Проверено на стенде перед этой миграцией: из 6 строк с непустым sketch ни в
одной нет ни знака замка, ни отключения CSS-фильтра, хотя у строк 5 и 18 замок
включён. То есть без пересчёта в списке осталась бы ровно та жалоба, ради
которой генератор и правили, а сам список выглядел бы вперемешку: старые
эскизы выворачивает фильтр тёмной темы, новые несут свой белый лист.

Почему не однострочник через _sync_snapshot_coating. Та функция переписывает
снимок, только если цвет покрытия в нём отличается от справочника; у строки 18
покрытие не выбрано вовсе, цвет и там и там пуст, функция выходит по continue
и снимка не касается — значит и зависимый sketch не пересчитывается. А замок
включён как раз у неё.

Повторный запуск безопасен: пересчёт кладёт в поле то же самое значение,
данные из снимка не меняются.
"""

from odoo import SUPERUSER_ID, api


def migrate(cr, version):
    env = api.Environment(cr, SUPERUSER_ID, {})
    lines = env["pmk.dobor.order.line"].search([])
    if not lines:
        return

    # Сначала цвет. Пунктир покрытия на эскизе красится по ключу paintHex из
    # снимка, а снимки, заведённые до появления ключа, его не содержат вовсе —
    # такой эскиз нарисовался бы служебным «покрытие не выбрано» при выбранном
    # покрытии. Заодно старые снимки получают нормализованный hex (правило —
    # dobor.normalize_hex).
    lines._sync_snapshot_coating()

    # Затем пересчёт. Метки «пересчитать» достаточно: flush_recordset сам
    # прогонит compute и запишет результат в базу (odoo/orm/models.py:
    # flush_recordset -> _recompute_recordset -> Field.recompute). Отдельный
    # invalidate_recordset не нужен — на входе в скрипт кэша поля нет, а
    # пересчёт всё равно перезаписывает значение.
    env.add_to_compute(lines._fields["sketch"], lines)
    lines.flush_recordset(["sketch"])
