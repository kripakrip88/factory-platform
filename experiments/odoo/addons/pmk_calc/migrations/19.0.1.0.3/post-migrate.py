"""Толщина позиции доборки = толщина выбранного металла (01.10.2026).

До этой версии толщину ставил onchange, а поля не было в видах — у всех
позиций, заведённых из формы, сохранялось умолчание 0,5. Печатный лист брал
из неё «Толщина, мм» и вес: на живой базе так печатались позиции 12
(ДОБ-00007, металл 0,40), 18 (ДОБ-00009, 0,45), 19 (ДОБ-00012, «Изготовлен»,
0,65) и 20 (ДОБ-00001, 0,40). Теперь поле вычисляемое от металла; здесь —
выправляем уже сохранённые строки. Через ORM, чтобы пересчитались зависимые
поля. Вес в форме не меняется: он и раньше шёл от металла (_mass_per_sqm).
Решение Антона: «по толщине металла конечно исправляй глюк».
Идемпотентно: трогаем только строки, где толщина расходится с металлом.
"""

from odoo import SUPERUSER_ID, api


def migrate(cr, version):
    env = api.Environment(cr, SUPERUSER_ID, {})
    lines = env["pmk.dobor.order.line"].with_context(active_test=False).search(
        [("sheet_id", "!=", False)])
    for line in lines:
        target = line.sheet_id.thickness_mm
        if target and abs((line.thickness or 0.0) - target) > 1e-6:
            line.thickness = target
