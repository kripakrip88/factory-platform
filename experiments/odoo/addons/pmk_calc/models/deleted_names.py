"""Имя строки, удалённой в этой же записи (разбор UX, шаг 30, доводка 02.10.2026).

ЗАЧЕМ. Изделия расчёта и позиции доборки — строки one2many, за которыми на
стенде следит своё отслеживание (tracking_manager; Настройки → Технические →
Модели, поля «Изделия» и «Доборки»). Ядро mail пишет такое поле в ленту
списком имён строк «было → стало» (mail.tracking.value._create_tracking_values)
и читает имена прежних строк перед фиксацией транзакции — уже после записи.
Имя удалённой строки к этому моменту из базы не прочитать: unlink()
сбрасывает весь кэш, чтение названия падает MissingError. Ядро ловит её в
mail.thread._message_track и молча пропускает ВСЕ отметки документа за это
сохранение: удалили позицию доборки и тем же нажатием сменили статус — в
ленте нет ни «Статус: Черновик → В работе», ни правки клиента или даты.

Позиция доборки так стала себя вести с шага 30 (имя — название позиции, а
не служебное «pmk.dobor.order.line,20», которое считалось без базы).
Изделие расчёта — давно: его имя всегда читалось из базы (поле name).

КАК. Перед удалением запоминаем имя строки в данных транзакции
(cr.precommit.data: их очищают сама фиксация, откат и прогон precommit), а
вычисление имени у удалённой строки берёт его оттуда. Не запомнили
(строку удалили в обход unlink() модели) — нейтральное слово, но не ошибка.
"""

KEY = "pmk_calc.deleted_names"


def remember(records):
    """Запомнить имена строк перед удалением — до конца транзакции."""
    names = records.env.cr.precommit.data.setdefault(KEY, {})
    for record in records:
        names[(record._name, record.id)] = record.display_name


def recall(record, fallback):
    """Имя удалённой строки: запомненное перед удалением, иначе ``fallback``."""
    names = record.env.cr.precommit.data.get(KEY, {})
    return names.get((record._name, record.id)) or fallback
